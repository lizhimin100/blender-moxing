"""
dg_layout.py —— 地牢入口 v2 **参数表**（唯一改数字的地方）

v2 的 parti（两轮改版后的定稿）：
  **一块石壳被凿开一道槽，槽的尽头两扇石门关着；门墙的两端埋进土坡里，
  顶上是一道塌掉的天际线 —— 它是从地底冒出来的，不是一段残墙。**

v1 → v2 推翻的四条：
  ① 主方向向上（抬台基 + 外爬梯 + 断塔）→ 改成**往下走的大踏步**；
  ② 语汇是联盟的（对称门楼 / 半圆拱 / 蓝旗）→ 轴线偏 0.12、没有塔没有旗；
  ③ 门是空的 → **两扇门关着** + 铜锁杠 + 门缝一线火；
  ④ 说不出"从地底冒出来" → 门墙**两端沉进土坡**、顶是阶梯状断脊、石壳缩到
     只剩槽口一圈，外面全是土（第二次改版加的那一刀：打掉"方墙"的读法）。

为什么这里有一张表：
  v1 的尺寸散在 40 个常量里，改一次门宽要同时动门洞 / 过梁 / 门套 / 门槛四处。
  这里只写"原料"，其余全部 `reflow()` 派生 —— 改 `open_hx` 一个数，
  过梁跨度、门扇宽、门套位置、门槛长度、踏步高度一起动。

坐标：X 右、Y 前（+Y = 正面，导出后 −Z）、Z 上；原点在占地中心，z = 0 地面。
交付前整体沿 X 镜像一次（与九座一致）。尺寸纪律见 `docs/地牢/v2/报告.md`。
"""

# ── 门墙的断脊（x0, x1, 顶高），从左到右 ────────────────────────────────────
# 每一段是"一皮砌体塌掉后剩下的平台"：段长 0.27–1.48 不等，落差 0.24–0.72。
# **两端（±3 附近）必须低于土坡面**，否则会露出一条方正的竖边 —— 那就又回到
# "残墙"的读法了。中央 4.84 是唯一的峰。
RIDGE = (
    (-3.08, -2.74, 2.18),
    (-2.74, -2.28, 2.56),
    (-2.28, -1.84, 3.30),
    (-1.84, -1.10, 4.10),
    (-1.10, -0.56, 4.36),
    (-0.56, 0.92, 4.84),
    (0.92, 1.86, 4.34),
    (1.86, 2.42, 3.80),
    (2.42, 3.05, 2.72),
    (3.05, 3.32, 2.10),
)


class Layout:
    # ── 石壳（只剩槽口一圈，外面交给土）────────────────────────────────────
    shelf_x = 3.95          # 石壳半宽（7.90）
    shelf_y0, shelf_y1 = -2.55, 4.05
    shelf_z = 1.38          # 石壳顶面 = 前庭的"地面线"
    shelf_band = 0.36       # 石壳下段的暗色带高（湿痕 / 土沁）

    # ── 前庭（下沉槽）：正面敞开，槽底就是 z≈0 ────────────────────────────
    pit_x = 2.10            # 槽半宽（4.20）
    pit_y0 = -0.06          # 槽底（= 门墙面）
    step_n = 3
    step_tread = 1.10
    pave_z = 0.18           # 槽底铺石面 = 门扇底 = 台阶落点
    coping_w = 0.34         # 槽口压边宽
    coping_h = 0.13         # 压边高出石壳面

    # ── 门墙 ──────────────────────────────────────────────────────────────
    gate_cx = 0.12          # 轴线偏移：整道墙比槽口偏右 12 cm —— 不是对称门楼
    gate_hx = 3.20          # 半宽（6.40）
    gate_y0 = -0.06
    gate_t = 1.14
    open_hx = 1.36          # 门洞半净宽（2.72）
    open_top = 3.42
    crown_top = 4.84        # 断脊的峰

    # ── 门扇 ──────────────────────────────────────────────────────────────
    door_t = 0.20
    door_recess = 0.50
    door_seam = 0.10
    door_open = 0.0         # ← **组件化开关**：0 = 关死；0.55 rad ≈ 31° 推开
    door_chip = 0.11

    # ── 队色（只两道，且只走水平顶面 + 一条门楣横线）──────────────────────
    team_runner_w = 0.36
    do_lean = 0.022         # 门墙 + 门扇整体左倾 1.26°（"沉降"的读法）

    # ── 土坡（把门墙两端吃掉的三座）────────────────────────────────────────
    # 土坡必须**高过门墙两端**（断脊两端 2.10–2.18），否则会露出一条方正的竖边；
    # 但又不能高过门套顶（3.42），否则门洞下沿被埋、读成"半地下的窗"。
    # 土坡分两段：**后高前低**。后面高到埋住门墙两端，前面塌到只到膝盖 ——
    # 这样正面看到的还是石头，土只在它背后"把它顶出来"。一整条等高土脊
    # 会把门夹成"土墙里的一个洞"，而且土是画面里最亮的东西，会抢主角。
    hill_l = (3.16, [(-4.86, -2.50), (-2.62, -2.50), (-2.62, 1.05),
                     (-4.92, 0.95), (-5.02, -1.10)])
    # 前段土坡要**没过石壳面**（1.38），只让槽口压边露一条线出来 ——
    # 这样正面的第一层读法是"土"，不是"石台"。石台一露就是平台。
    hill_lf = (1.62, [(-4.44, 0.92), (-2.50, 0.98), (-2.50, 3.35),
                      (-3.42, 3.62), (-4.30, 2.95)])
    hill_r = (3.02, [(2.62, -2.50), (4.90, -2.55), (4.96, 1.05),
                     (2.62, 1.05), (2.62, -0.10)])
    hill_rf = (1.58, [(2.50, 0.98), (4.86, 1.02), (4.36, 2.92),
                      (3.38, 3.62), (2.50, 3.35)])
    hill_b = (2.96, [(-4.30, -1.05), (4.30, -1.10), (4.20, -3.10),
                     (3.40, -4.30), (0.60, -4.45), (-2.20, -4.38),
                     (-3.70, -3.90), (-4.35, -2.60)])

    def __init__(self, **over):
        for k, v in over.items():
            if not hasattr(Layout, k):
                raise KeyError("Layout 没有这个参数：%s" % k)
            setattr(self, k, v)
        self.reflow()

    def reflow(self):
        """派生量：所有"跟着原料走"的尺寸只在这里算一次。"""
        # 台阶：踏高由"石壳面到铺石面"均分 —— 改层高自动跟上，不会差一级
        self.step_rise = (self.shelf_z - 0.01 - self.pave_z) / self.step_n
        self.pit_w = self.pit_x * 2
        self.pit_y1 = self.shelf_y1
        self.step_run = self.step_n * self.step_tread
        self.floor_z = 0.10
        self.pit_floor_y1 = self.pit_y1 - self.step_run

        # 门墙
        self.gate_x0 = self.gate_cx - self.gate_hx
        self.gate_x1 = self.gate_cx + self.gate_hx
        self.gate_y1 = self.gate_y0 - self.gate_t
        self.open_x0 = self.gate_cx - self.open_hx
        self.open_x1 = self.gate_cx + self.open_hx
        self.open_w = self.open_hx * 2

        # 门扇
        self.door_z0 = self.pave_z
        self.door_top = self.open_top - 0.10
        self.door_h = self.door_top - self.door_z0
        self.leaf_w = (self.open_w - self.door_seam) * 0.5 - 0.012
        self.door_hy = self.gate_y0 - self.door_recess
        self.leaf_hinge = (self.gate_cx - self.door_seam * 0.5,
                           self.gate_cx + self.door_seam * 0.5)

        # 门套
        self.frame_w = 0.32
        self.frame_pr = 0.22
        self.lintel_h = 0.58
        self.lintel_z0 = self.open_top
        self.lintel_z1 = self.open_top + self.lintel_h

        # 队色中带
        self.runner_y0 = self.gate_y0 + 0.04
        self.runner_y1 = self.pit_floor_y1

    @property
    def height(self):
        return self.crown_top


L = Layout()
