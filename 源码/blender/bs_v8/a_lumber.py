def _log(B, name, p0, p1, r, role="木", sides=6, cap="木亮"):
    """横躺的原木：六边棱柱 + 两端口。

    不用 akit.log_axis 的两个原因：① 它把年轮片推到 2 mm 外，体检判悬空；
    ② 8 边在原木堆里最贵，六边在 96 px 上一样是"圆端面"。
    """
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    L = d.length
    if L < 1e-6:
        return
    q = d.to_track_quat('Z', 'Y').to_matrix()
    v = []
    for s in (0.0, L):
        for i in range(sides):
            a = 2 * math.pi * i / sides + math.pi / sides
            v.append(tuple(p0 + q @ Vector((r * math.cos(a), r * math.sin(a), s))))
    f = []
    for i in range(sides):
        j = (i + 1) % sides
        f.append((i, j, sides + j, sides + i))
    f.append(tuple(range(sides - 1, -1, -1)))
    f.append(tuple(range(sides, 2 * sides)))
    B.part(name, v, f, role, 0.0, 1, "all")
    for k, p in ((0, p0), (1, p1)):
        sgn = -1 if k == 0 else 1
        off = p + d.normalized() * 0.0012 * sgn
        vv = []
        for i in range(sides):
            a = 2 * math.pi * i / sides + math.pi / sides
            vv.append(tuple(off + q @ Vector((r * 0.60 * math.cos(a),
                                              r * 0.60 * math.sin(a), 0.0))))
        B.part(name + "芯%d" % k, vv, [tuple(range(sides))], cap, 0.0, 1, "all")


def _logpile(B, at, z=G, n=3, length=0.170, r=0.020, rot=0.0, layers=2):
    """原木堆：端面朝 +X，逐层收一朵 —— 圆端面就是"木头"的唯一证据。"""
    x, y = at
    m = Matrix.Rotation(rot, 3, 'Z')
    for k in range(layers):
        cnt = n - k
        for i in range(cnt):
            u = (i - (cnt - 1) / 2) * (r * 2.06)
            p = m @ Vector((-length / 2, u, 0))
            p2 = m @ Vector((length / 2, u, 0))
            _log(B, "原木%d%d" % (k, i),
                 (x + p.x, y + p.y, z + r + k * r * 1.74),
                 (x + p2.x, y + p2.y, z + r + k * r * 1.74), r, "木", 6)


def _plank_stack(B, at, z=G, n=3, w=0.250, d=0.058, t=0.014):
    """成堆木板：每块左右错 5 mm、上下只留 1 mm —— 紧贴才读"一摞板"，
    底下垫高就会读成"长凳"（v1 的老坑）。"""
    x, y = at
    for i in range(n):
        xx = x + ((0.005, -0.005, 0.008)[i % 3])
        B.box("木板%d" % i, w, d, t, z + i * (t + 0.001), "木亮", 0.0, at=(xx, y))


def _trestle(B, at, z=G, h=0.150, span=0.190, r=0.024):
    """锯木架：两副 A 字腿夹一根原木（原木沿 X，腿在 YZ 面交叉）。"""
    x, y = at
    for s in (-1, 1):
        B.beam("锯架腿%d" % s, (x + s * span / 2, y - 0.055, z),
               (x + s * span / 2, y + 0.004, z + h), 0.022, 0.020, "木暗")
        B.beam("锯架腿后%d" % s, (x + s * span / 2, y + 0.055, z),
               (x + s * span / 2, y - 0.004, z + h - 0.008), 0.022, 0.020, "木暗")
    _log(B, "架上原木", (x - 0.120, y, z + h + 0.010),
         (x + 0.120, y, z + h + 0.010), r, "木", 6)
    # 锯：一片薄铁板咬进原木顶 + 一根木柄
    B.plate("手锯板", [(-0.052, 0.0), (0.052, 0.0), (0.052, 0.022), (0.020, 0.030),
                       (-0.052, 0.016)], 0.005, "铁亮",
            (x + 0.004, y + 0.008, z + h + 0.020), "Y")
    B.beam("锯柄", (x - 0.060, y + 0.008, z + h + 0.030),
           (x - 0.096, y + 0.008, z + h + 0.048), 0.011, 0.011, "木暗")


def _block(B, at, z=G):
    """斧劈墩：树桩 + 嵌进墩面的斧（斧头是楔形，柄斜插）。"""
    x, y = at
    akit.stump(B, (x, y), z, 0.030, 0.026)
    B.beam("斧柄", (x + 0.004, y, z + 0.040), (x + 0.044, y, z + 0.096),
           0.010, 0.010, "木暗")
    B.plate("斧头", [(-0.008, 0.006), (0.012, 0.006), (0.016, -0.014),
                     (0.000, -0.020), (-0.010, -0.012)], 0.007, "铁",
            (x + 0.008, y, z + 0.052), "Y")


def _saw_frame(B, face_y, cx, zb, zt, r=0.080, teeth=10):
    """正面外挑木架 + 立式圆锯。

    锯盘**挂在墙外 4 cm 的挑架上**（上下两根挑臂 + 一根吊柱），盘面朝 +Y：
    整圆都在墙外，半个圆以上一定看得见 —— 这是伐木场的第一识别件。
    吊柱咬进挑臂、盘心咬进吊柱、挑臂咬进墙面，三件串成一条，谁都不悬空。
    """
    zc = zb + (zt - zb) * 0.52
    # 暗木背板：米白墙前面放一块深色板，96 px 上铁盘才不是一个灰点
    B.box("锯背板", 2 * r + 0.030, 0.012, 2 * r + 0.030, zc - r - 0.015, "木", 0.0,
          at=(cx, face_y + 0.016))
    for s in (-1, 1):
        B.box("挑臂%d" % s, 0.058, 0.050, 0.028, zc + s * (r + 0.020), "木暗", 0.0,
              at=(cx, face_y + 0.021))
    # 吊柱必须**退到盘面之后**（前沿 0.039 < 盘背 0.038+1 mm）：v2 把柱放在盘前面，
    # 一根 4 cm 宽的深色柱子把圆盘劈成两半，看着像两片扇叶。
    B.box("吊柱", 0.040, 0.026, 2 * r + 0.062, zc - r - 0.031, "木暗", 0.0,
          at=(cx, face_y + 0.026))
    B.beam("锯轴", (cx, face_y + 0.010, zc), (cx, face_y + 0.046, zc),
           0.018, 0.018, "铁")
    akit.saw_blade(B, (cx, face_y + 0.043, zc), r, "Y", teeth)


def _cart(B, at, z=G, w=0.126, d=0.066):
    """板车：车斗 + 两侧木轮 + 车辕。轮子是**立在 YZ 面的圆盘**（axis='X'）。"""
    x, y = at
    B.box("车斗", w, d, 0.034, z + 0.022, "木", 0.0, at=(x, y))
    B.box("斗沿", w + 0.008, d + 0.008, 0.008, z + 0.054, "木亮", 0.0, at=(x, y))
    for s in (-1, 1):
        B.disc("车轮%d" % s, 0.026, 0.014, (x, y + s * (d / 2 + 0.005), z + 0.026),
               "木暗", 6, "X")
    B.beam("车辕", (x + w / 2 - 0.004, y, z + 0.038), (x + w / 2 + 0.072, y, z + 0.028),
           0.012, 0.012, "木暗")


def _ramp(B, at, z0, z1, w=0.130, d=0.240, role="木"):
    """原木坡道：一块厚板 + 两根侧帮（板厚 ≥ 0.02，不许纸片）。"""
    x, y = at
    hw, hd = w / 2, d / 2
    B.slab4("坡道板", [(x - hw, y - hd, z1), (x + hw, y - hd, z1),
                       (x + hw, y + hd, z0), (x - hw, y + hd, z0)], 0.022, role)
    for s in (-1, 1):
        B.slab4("坡道帮%d" % s, [(x + s * (hw - 0.006), y - hd, z1 + 0.014),
                                 (x + s * (hw + 0.006), y - hd, z1 + 0.014),
                                 (x + s * (hw + 0.006), y + hd, z0 + 0.014),
                                 (x + s * (hw - 0.006), y + hd, z0 + 0.014)],
                0.030, "木暗")


# ================================================================ 1★ 敞棚

def s1(B):
    """四柱敞棚 + 大坡蓝瓦顶 + 原木堆 + 锯木架 + 斧劈墩。

    敞棚只做一面背板：正面、左右两面全开，锯木架就摆在开着的正前方 ——
    "棚"必须能看进去，封上就变仓库。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.760, 0.680, at=(0.0, 0.010))
        akit.apron(B, 0.230, 0.096, G, "石暗", (0.0, 0.368))

    SX, SY = -0.050, -0.060
    PX, PY = 0.225, 0.200
    ZP = 0.452

    with B.group("棚架"):
        for sx in (-1, 1):
            for sy in (-1, 1):
                B.box("木柱%d%d" % (sx, sy), 0.056, 0.056, ZP - G, G, "木暗", 0.006,
                      at=(SX + sx * PX, SY + sy * PY))
        # 纵枋顶 0.446，柱顶 0.452：差 6 mm 是"梁压在柱上"，同高就判共面
        for sy in (-1, 1):
            B.box("纵枋%d" % sy, 0.510, 0.056, 0.044, ZP - 0.050, "木", 0.0,
                  at=(SX, SY + sy * PY))
        for sx in (-1, 1):
            B.box("横枋%d" % sx, 0.056, 0.410, 0.040, ZP - 0.050, "木", 0.0,
                  at=(SX + sx * PX, SY))
        # 斜撑：从柱脚斜到纵枋下 —— 有斜撑才读"木架"，没有就是一排柱子
        for sx in (-1, 1):
            for sy in (-1, 1):
                B.beam("斜撑%d%d" % (sx, sy),
                       (SX + sx * (PX - 0.010), SY + sy * (PY - 0.020), ZP - 0.176),
                       (SX + sx * (PX - 0.088), SY + sy * (PY - 0.020), ZP - 0.058),
                       0.020, 0.024, "木")

    with B.group("背板"):
        for i in range(4):
            B.box("背板%d" % i, 0.098, 0.024, 0.330, G, "木", 0.0,
                  at=(SX + (i - 1.5) * 0.112, SY - PY + 0.010))
        for k in range(2):
            B.box("背枋%d" % k, 0.432, 0.026, 0.024, G + 0.086 + k * 0.150, "木暗", 0.0,
                  at=(SX, SY - PY - 0.008))

    with B.group("屋顶"):
        akit.tiled_roof(B, 0.560, 0.520, ZP + 0.002, ZP + 0.164, at=(SX, SY),
                        n=4, ridge="木暗", gable="灰泥", barge_back=False)

    with B.group("棚内"):
        # 工作台 + 台上原木 + 台下木箱：棚里必须"有活干"
        B.box("工作台", 0.230, 0.120, 0.026, G + 0.230, "木亮", 0.0,
              at=(SX + 0.080, SY - 0.090))
        for s in (-1, 1):
            B.box("台腿%d" % s, 0.024, 0.024, 0.230, G, "木暗", 0.0,
                  at=(SX + 0.080 + s * 0.094, SY - 0.090))
        _log(B, "台上原木", (SX - 0.020, SY - 0.090, G + 0.268),
             (SX + 0.170, SY - 0.090, G + 0.268), 0.019, "木", 6)

    with B.group("锯木架"):
        _trestle(B, (0.020, 0.276))

    with B.group("斧劈墩"):
        _block(B, (-0.302, 0.286))

    with B.group("原木堆"):
        _logpile(B, (0.290, 0.046), G, 3, 0.168, 0.023, 0.0, 2)
        _log(B, "散木", (0.212, 0.170, G + 0.020), (0.362, 0.170, G + 0.020),
             0.020, "木", 6)

    with B.group("道具"):
        _plank_stack(B, (-0.286, 0.392), G, 3, 0.190, 0.052, 0.013)
        akit.crate(B, (0.318, 0.330), G, 0.054, 0.046)
        akit.barrel(B, (0.212, 0.398), G, 0.024, 0.052)
        akit.wall_banner(B, (SX + PX + 0.002, SY + 0.010, ZP - 0.060),
                         0.046, 0.078, axis="X")


