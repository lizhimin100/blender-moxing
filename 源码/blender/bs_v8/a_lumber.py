def s2(B):
    """石砌基座 + 木构上层 + 立式圆锯 + 原木坡道 + 成堆木板。

    1★→2★ 的三件事：**墙换石**（台基/墙裙/隅石一整圈）、**圆锯上墙**（第二识别件）、
    **多一层工作平台**（原木从坡道滚上去）。屋顶语法不动 —— 还是那顶大坡瓦顶。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.800, 0.740, at=(0.0, 0.006))
        akit.apron(B, 0.260, 0.100, G, "石暗", (0.0, 0.380))
        B.box("料场", 0.230, 0.150, 0.008, G, "沙", 0.0, at=(0.300, 0.320))

    HX, HY = -0.020, -0.055
    BW, BD = 0.560, 0.400

    with B.group("石基"):
        zt = akit.stone_wall(B, BW, BD, G, 0.162, at=(HX, HY), skirt=0.048,
                             plinth_h=0.030)

    with B.group("木架上层"):
        zt2 = akit.timber_wall(B, 0.500, 0.340, zt, 0.286, at=(HX, HY),
                               studs=2, brace=True, rail=0.54, t=0.018)
        B.box("上层檐影", 0.520, 0.360, 0.011, zt2 - 0.002, "木暗", 0.0, at=(HX, HY))

    with B.group("圆锯"):
        _saw_frame(B, HY + 0.170, HX, zt + 0.030, zt2 - 0.012, 0.075)

    with B.group("屋顶"):
        akit.tiled_roof(B, 0.580, 0.470, zt2 + 0.009, zt2 + 0.198, at=(HX, HY),
                        n=4, ridge="木暗", gable="灰泥", barge_back=False)

    with B.group("坡道"):
        _ramp(B, (0.296, 0.238), G + 0.004, G + 0.230, 0.120, 0.230)
        _log(B, "坡道原木", (0.296, 0.128, G + 0.238), (0.296, 0.330, G + 0.058),
             0.023, "木", 6)

    with B.group("原木堆"):
        _logpile(B, (-0.330, 0.086), G, 2, 0.150, 0.020, 0.0, 2)

    with B.group("木板"):
        _plank_stack(B, (0.320, 0.330), G, 3, 0.200, 0.056, 0.014)
        _plank_stack(B, (0.030, 0.392), G, 2, 0.180, 0.050, 0.013)

    with B.group("道具"):
        akit.barrel(B, (-0.352, 0.300), G, 0.024, 0.054)
        akit.crate(B, (-0.250, 0.376), G, 0.052, 0.044)
        akit.win(B, 0.046, 0.054, (HX + 0.250, HY + 0.026, zt + 0.086), "洞", None, "X")
        akit.wall_banner(B, (HX + 0.176, HY + 0.176, zt2 - 0.020), 0.044, 0.070)


