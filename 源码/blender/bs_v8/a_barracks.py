"""a_barracks.py —— 兵营 · 三档（非塔类）

母题：**重型石砌拱门要塞 + 半封闭演武前庭 + 粗壮斜撑**。
这不是民房。三条铁律：

    1. **一次三角屋顶都不给正面**。正面永远是"墙 + 拱门 + 垛口"。
       三角屋顶一出现在正立面，不管加多少长矛都会读成农舍。
    2. **拱门必须是整栋最宽的东西**（1★ 0.24 / 2★ 0.26 / 3★ 0.30），
       门洞比窗大三倍，这才叫"门"。
    3. **前庭是空的**。场地中央留一块沙地，武器架与木人贴边站 ——
       空地本身就是"演武场"的证据，塞满道具反而读成仓库。

三档递进（高度只涨 0.09 / 0.14，占地涨 0.10 / 0.10）：
    1★ 木石营棚：矮墙 + 大拱 + 平顶垛口 + 木栏        高 0.61
    2★ 石砌营房：阶梯扶壁 + 半层蓝瓦军械库 + 矮石墙    高 0.82
    3★ 皇家要塞：双层城门楼 + 双哨堡 + 铁栅 + 金交叉剑  高 0.99
"""
import math

import bpy

import akit
from akit import Z0, TY, G          # noqa: F401


def _sand(B, r, at, z=G):
    """操练沙地：一块浅色薄盘。空着才是"空地"。"""
    B.cyl("沙地", r, 0.004, z, 10, "沙", at=at)


def _rail(B, x0, x1, y, z, n=4, h=0.052, role="木暗"):
    """木栏：立柱 + 一道横杆。平顶营房靠它区别于"石头盒子"。"""
    for i in range(n):
        x = x0 + (x1 - x0) * (i / max(1, n - 1))
        B.box("栏柱", 0.012, 0.012, h, z, role, 0.0, at=(x, y))
    B.box("栏横", abs(x1 - x0) + 0.014, 0.010, 0.010, z + h - 0.008, role, 0.0,
          at=((x0 + x1) / 2, y))


def _gate_hole(B, x, y, w, h, z0, inner="炭", floor="土"):
    """真开洞的拱门：暗拱板（退 6 mm）+ 洞底一条地面 + 洞内一点暖光。

    不做布尔运算。1 m 件上挖真洞只会破面；"暗 + 地面 + 一点暖光"
    三件齐了，眼睛自己会把洞补成"里面有个院子"。
    """
    akit.arch_gate(B, (x, y), w, h, z0, ring=0.026, dark=inner, keystone=True)
    B.box("洞底", w * 0.94, 0.030, 0.006, z0 + 0.001, floor, 0.0, at=(x, y + 0.004))
    # 洞里一点火盆：暖色是唯一能在大白天读出"里面有人"的东西（两槽制没有自发光）
    B.box("门内火盆", 0.018, 0.014, 0.020, z0 + 0.012, "炉", 0.0,
          at=(x - w * 0.28, y + 0.002))


# ================================================================ 1★ 木石营棚

def s1(B):
    """矮营棚 + 夸张宽大的半圆拱门 + 平顶垛口 + 木栏。

    正立面是**一整片墙**：石脚 → 木构 → 拱门 → 平顶垛口。没有山墙、没有瓦坡。
    屋顶只做"平顶 + 一圈矮垛 + 木栏"，从任何角度看都不像民房。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.740, 0.700, at=(0.0, 0.015))
        _sand(B, 0.120, (0.020, 0.205))
        akit.fence(B, -0.360, -0.180, 0.352, G, 0.104, 2, 2)
        akit.fence(B, 0.180, 0.360, 0.352, G, 0.104, 2, 2)

    HW, HD, HY = 0.540, 0.340, -0.155
    YF = HY + HD / 2                       # 0.015 正面

    with B.group("营棚"):
        B.box("石脚", HW + 0.036, HD + 0.036, 0.058, G, "石暗", 0.008, at=(0.0, HY))
        zt = akit.timber_wall(B, HW, HD, G + 0.054, 0.286, at=(0.0, HY),
                              studs=3, brace=False, rail=0.56)
        # 正面的木构要更密：这一面是兵营的"脸"，稀稀拉拉三根柱子就是民房
        for i in range(4):
            u = -HW / 2 + HW * (i + 0.5) / 4
            B.box("正立枋%d" % i, 0.016, 0.018, 0.286, G + 0.054, "木暗", 0.0,
                  at=(u, YF + 0.006))
        B.box("正腰枋", HW - 0.010, 0.018, 0.016, G + 0.054 + 0.150, "木暗", 0.0,
              at=(0.0, YF + 0.006))

    with B.group("拱门"):
        _gate_hole(B, 0.0, YF, 0.240, 0.272, G + 0.006)
        # 门棚：两根斜撑挑一块队色布篷。队色面积 + 门面厚度，一块布干两件事。
        B.slab4("门棚", [(-0.190, YF + 0.004, G + 0.322),
                         (0.190, YF + 0.004, G + 0.322),
                         (0.166, YF + 0.098, G + 0.282),
                         (-0.166, YF + 0.098, G + 0.282)], 0.008, "旗")
        for s in (-1, 1):
            B.beam("棚撑%d" % s, (s * 0.150, YF + 0.080, G + 0.276),
                   (s * 0.150, YF + 0.010, G + 0.312), 0.010, 0.010, "木暗")
            akit.shield(B, (s * 0.212, YF + 0.006, G + 0.196), 0.044)

    with B.group("平顶"):
        # 平顶 + 正面垛口 + 两侧木栏：**没有一片斜瓦**，这是"营"不是"宅"
        # 平顶 = **矮四坡蓝瓦 + 一圈垛口**：正面看不到山墙，但看得见瓦。
        # 纯石头平顶会让队色掉到 0.4%，而"队色只在一面旗上"是换阵营时最先崩的地方。
        B.box("顶檐", HW + 0.058, HD + 0.054, 0.012, G + 0.332, "木暗", 0.0,
              at=(0.0, HY))
        B.roof_hip("顶面", HW + 0.036, HD + 0.032, G + 0.340, G + 0.392, "瓦",
                   0.0, (0.0, HY))
        # 女儿墙：没有这一道 5 cm 的石带，垛口就是"摆在屋面上的骰子"
        B.box("女墙", HW + 0.062, 0.032, 0.048, G + 0.336, "石", 0.0,
              at=(0.0, YF + 0.012))
        akit.crenel(B, "顶垛", -0.238, 0.238, YF + 0.010, G + 0.382, 5,
                    0.030, 0.040, 0.034)
        for s in (-1, 1):
            _rail(B, HY - 0.120, HY + 0.110, HY + s * (HD / 2 + 0.010),
                  G + 0.366, 3, 0.048)

    with B.group("旗帜"):
        akit.flag_pole(B, (-0.196, HY), G + 0.366, G + 0.524, 0.078, 0.062)
        B.plate("门旗", [(-0.104, 0.0), (0.104, 0.0), (0.104, -0.050),
                        (0.0, -0.064), (-0.104, -0.050)], 0.008, "旗",
                (0.0, YF + 0.010, G + 0.360), "Y")

    with B.group("道具"):
        akit.rack(B, (0.290, 0.108), G, 0.132, 0.148, 3, True)
        akit.dummy(B, (-0.286, 0.210), G, 0.214)
        akit.barrel(B, (0.330, 0.276), G)
        akit.crate(B, (-0.330, 0.086), G, 0.056, 0.048)


# ================================================================ 2★ 石砌营房

def s2(B):
    """全面石质化 + 阶梯扶壁 + 半层蓝瓦军械库 + 矮石前庭。

    1★→2★ 的三件事：**墙换石**、**拱门两侧长出阶梯扶壁**（受力感）、
    **屋顶长出一层军械库**（不是把主墙拔高，是在后面叠半层）。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.800, 0.760, at=(0.0, 0.010))
        _sand(B, 0.116, (0.010, 0.238))
        for s in (-1, 1):
            akit.wall_low(B, 0.030, 0.300, G, 0.070, "石暗", "石",
                          at=(s * 0.372, 0.170))
        akit.wall_low(B, 0.240, 0.030, G, 0.070, "石暗", "石", at=(-0.205, 0.330))
        akit.wall_low(B, 0.240, 0.030, G, 0.070, "石暗", "石", at=(0.205, 0.330))

    HW, HD, HY = 0.600, 0.340, -0.150
    YF = HY + HD / 2                       # 0.020

    with B.group("石营"):
        zt = akit.stone_wall(B, HW, HD, G, 0.330, at=(0.0, HY), skirt=0.058)
        akit.win(B, 0.044, 0.052, (HW / 2, HY + 0.020, G + 0.170), "洞", "石亮", "X")
        akit.win(B, 0.036, 0.046, (-HW / 2, HY + 0.020, G + 0.170), "洞", None, "X")

    with B.group("拱门"):
        _gate_hole(B, 0.0, YF, 0.256, 0.286, G + 0.006)
        for s in (-1, 1):
            # 阶梯扶壁：两段，下段更深。斜顶 + 台阶 = "在受力"
            akit.buttress(B, (s * 0.176, YF - 0.004), 0.062, 0.330, 0.056,
                          sgn=1, steps=2)
            akit.shield(B, (s * 0.238, YF + 0.006, G + 0.250), 0.040)

    with B.group("军械库"):
        # 后半层：box 叠在石墙上，再压蓝瓦 —— 高度只加 0.16，占地不加
        AW, AD, AY = 0.400, 0.270, -0.196
        B.box("库身", AW, AD, 0.170, G + 0.318, "石", 0.008, at=(0.0, AY))
        B.box("库檐", AW + 0.034, AD + 0.030, 0.012, G + 0.486, "石亮", 0.0,
              at=(0.0, AY))
        akit.tiled_roof(B, AW + 0.098, AD + 0.092, G + 0.494, G + 0.610,
                        at=(0.0, AY), n=3, ridge="石亮", gable="灰泥",
                        barge_back=False, gable_window=0.026)
        akit.win(B, 0.040, 0.048, (AW / 2, AY + 0.006, G + 0.372), "洞", None, "X")

    with B.group("平顶"):
        B.box("顶檐", HW + 0.052, HD + 0.048, 0.011, G + 0.336, "木暗", 0.0,
              at=(0.0, HY))
        akit.crenel(B, "顶垛", -0.256, 0.256, YF - 0.006, G + 0.352, 5,
                    0.030, 0.034, 0.030)

    with B.group("旗帜"):
        # 门楣门旗：不是装饰，是队色面积的"保险"。只靠两面小墙旗时队色只有 9.9%。
        B.plate("门旗", [(-0.115, 0.0), (0.115, 0.0), (0.115, -0.062),
                        (0.0, -0.078), (-0.115, -0.062)], 0.008, "旗",
                (0.0, YF + 0.012, G + 0.344), "Y")
        akit.wall_banner(B, (-0.286, YF + 0.006, G + 0.322), 0.056, 0.096)
        akit.wall_banner(B, (0.286, YF + 0.006, G + 0.322), 0.056, 0.096)
        akit.flag_pole(B, (0.190, HY), G + 0.598, G + 0.742, 0.070, 0.058)

    with B.group("道具"):
        akit.rack(B, (0.286, 0.116), G, 0.140, 0.156, 3, True)
        akit.dummy(B, (-0.286, 0.238), G, 0.222)
        akit.barrel(B, (0.352, 0.284), G)


# ================================================================ 3★ 皇家要塞

def s3(B):
    """双层城门楼 + 双哨堡 + 铁栅 + 金交叉剑盾徽 + 后方蓝瓦营房。

    这是七座里唯一"正面是一道墙"的建筑。层次从下往上：
        台基 0.14 → 门墙 0.46 → 城楼 0.72 → 哨堡锥顶 0.78 → 主脊 0.62（在墙后）
    前庭被门墙挡住，所以道具全部摆到**门外两侧**，别浪费在看不见的院子里。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.900, 0.880, at=(0.0, 0.004))
        B.box("门前道", 0.300, 0.100, 0.006, G, "石暗", 0.0, at=(0.0, 0.410))

    with B.group("营房"):
        # 后方营房退到门墙后：只露蓝瓦顶，制造纵深
        # 后墙被门墙完全遮住，只露屋顶：不做台基/隅石/檐口，省 160 tri
        W, D, YC = 0.620, 0.340, -0.220
        B.box("营房身", W, D, 0.330, G + 0.030, "石", 0.008, at=(0.0, YC))

        akit.tiled_roof(B, W + 0.090, D + 0.086, G + 0.356, G + 0.546,
                        at=(0.0, YC), n=2, ridge="金", gable="灰泥",
                        barge_back=False)

    with B.group("门墙"):
        GW, GD, GY = 0.760, 0.150, 0.286
        B.box("门墙", GW, GD, 0.360, G, "石暗", 0.008, at=(0.0, GY))
        B.box("门墙裙", GW + 0.024, GD + 0.022, 0.062, G, "台基", 0.0, at=(0.0, GY))
        for s in (-1, 1):
            akit.crenel(B, "墙垛%d" % s, s * 0.170, s * 0.330, GY,
                        G + 0.362, 3, 0.030, 0.036, 0.032)
            # 阶梯扶壁压在门墙两端，把"一道墙"钉进地里
            akit.buttress(B, (s * 0.330, GY + GD / 2 - 0.006), 0.058, 0.300,
                          0.048, sgn=1, steps=2)

    with B.group("城楼"):
        # 中央城楼：门墙之上再起一层（0.46 → 0.72），顶上垛口
        TW, TD, TY = 0.300, 0.190, 0.272
        B.box("城楼身", TW, TD, 0.280, G + 0.366, "石", 0.008, at=(0.0, TY))
        B.box("城楼裙", TW + 0.024, TD + 0.020, 0.034, G + 0.366, "石暗", 0.0,
              at=(0.0, TY))
        B.box("城楼檐", TW + 0.030, TD + 0.026, 0.013, G + 0.644, "石亮", 0.0,
              at=(0.0, TY))
        akit.crenel(B, "城楼垛", -0.120, 0.120, TY + TD / 2 - 0.015,
                    G + 0.658, 3, 0.032, 0.040, 0.034)
        akit.flag_pole(B, (0.0, TY), G + 0.660, G + 0.870, 0.100, 0.084)


    with B.group("哨堡"):
        # 两座矮胖哨堡：比城楼矮 0.06，蓝锥顶把左右两角"封住"
        for s in (-1, 1):
            at = (s * 0.356, GY + 0.020)
            top = akit.tower_sq(B, at, 0.170, 0.180, G, 0.480, cap="pyramid",
                                cap_h=0.078, at_name="哨堡%d" % s)
            akit.win(B, 0.016, 0.042, (at[0], at[1] + 0.090, G + 0.300),
                     "洞", None, "Y")
            _ = top

    with B.group("城门"):
        YG = GY + GD / 2                   # 0.361
        # 门里必须有**木门扇**：只有铁栅 + 黑洞会读成"窗棂"（v1 就栽在这）。
        # 木门在下、铁栅在上，才读"闸门后面是门"。
        akit.arch_gate(B, (0.0, YG), 0.300, 0.300, G + 0.062, ring=0.030,
                       doors=True, door_role="木暗")
        akit.portcullis(B, (0.0, YG + 0.010), 0.272, 0.292, G + 0.070,
                        bars=3, rails=2)
        # 门楣上方：金交叉巨剑 + 盾徽（三层：金背板 / 队色盾 / 金剑）
        akit.crest(B, (0.0, YG + 0.008, G + 0.392), 0.190, 0.090, kind="swords")
        akit.steps(B, 0.260, 2, G, G + 0.062, YG + 0.002, YG + 0.070, "台基")

    with B.group("旗帜"):
        for s in (-1, 1):
            akit.wall_banner(B, (s * 0.228, GY + GD / 2 + 0.006, G + 0.340),
                             0.054, 0.116)
        akit.banner_stand(B, (-0.404, 0.408), G, 0.238, 0.054, 0.084)

    with B.group("道具"):
        akit.dummy(B, (-0.376, 0.150), G, 0.206)



# ================================================================ 装配

def build(star, pal=None):
    B = akit.new(pal)
    {1: s1, 2: s2, 3: s3}[star](B)
    ob = B.join("兵营_%d星" % star)
    return ob, B


