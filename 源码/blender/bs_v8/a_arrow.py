"""a_arrow.py —— 箭塔 · 三档（塔类）

母题：**全石矮壮箭塔 + 出挑木斗堡 + 弩炮**。
和哨塔的分工（必须一眼分开，否则两座塔在场上互为噪音）：

    哨塔 = 偏木、偏瘦、**开放式瞭望平台**（看得见栏杆和梯子）
    箭塔 = 全石、矮壮、**封闭垛口 + 木斗堡 + 弩炮**（看得见武器）

三档递进：
    1★ 石塔 + 单面木斗堡 + 4 垛            高 0.95
    2★ 加高 + 双耳斗堡（蓝锥顶）+ 腰线      高 1.16
    3★ 厚塔 + 四角小塔 + 出挑托石 + 弩炮    高 1.38
"""
import math

import bpy

import akit
from akit import Z0, TY, G          # noqa: F401


def _slit(B, x, y, z, w=0.016, h=0.044, axis="Y"):
    """箭孔：一条窄黑缝 + 一圈浅石框。塔身没有它会读成烟囱。"""
    ax = "Y" if axis == "Y" else "X"
    akit.win(B, w, h, (x, y, z), "洞", None, ax)
    if ax == "Y":
        B.box("孔楣", w + 0.020, 0.014, 0.008, z + h, "石亮", 0.0, at=(x, y + 0.002))
    else:
        B.box("孔楣", 0.014, w + 0.020, 0.008, z + h, "石亮", 0.0, at=(x + 0.002, y))


def _hoarding(B, at, w=0.300, z=0.0, h=0.110, proj=0.052, n=3):
    """木斗堡：悬挑在塔身外的木构射击廊。

    三条死线（v1 全踩过）：
      · **进深 ≤0.05**：做到 0.07 就变"挂在墙上的木箱"；
      · **高度 ≤0.11**：比这高就是阳台，不是射击廊；
      · **必须有托木**：3 根斜撑是"挑出来"的唯一证据，少了就贴在墙上。
    位置要**贴着垛口下沿**（调用方给 z），挂在塔腰上会读成招牌。
    """
    x, y = at
    y1 = y + proj
    B.box("斗堡", w, proj + 0.016, h, z, "木", 0.0, at=(x, y + proj / 2))
    B.box("斗堡底", w + 0.008, proj + 0.024, 0.010, z - 0.008, "木暗", 0.0,
          at=(x, y + proj / 2))
    B.box("斗堡檐", w + 0.012, proj + 0.030, 0.010, z + h - 0.006, "木亮", 0.0,
          at=(x, y + proj / 2))
    B.box("斗堡栏", w + 0.006, 0.012, 0.014, z + h - 0.018, "木亮", 0.0,
          at=(x, y1 - 0.004))
    for i in range(n):
        u = -w / 2 + w * (i + 0.5) / n
        B.beam("斜撑%d" % i, (x + u, y + 0.002, z - 0.074),
               (x + u, y1 - 0.008, z - 0.010), 0.014, 0.014, "木暗")


def _ballista(B, at, z, s=1.0):
    """弩炮：底座 + 弩臂 + 两根弓臂 + 一支弩箭。塔顶的"武器"，3★ 专用。"""
    x, y = at
    B.box("弩座", 0.070 * s, 0.080 * s, 0.024, z, "木暗", 0.0, at=(x, y))
    B.box("弩身", 0.030 * s, 0.200 * s, 0.026, z + 0.022, "木", 0.0, at=(x, y))
    for sx in (-1, 1):
        B.beam("弩臂%d" % sx, (x + sx * 0.020 * s, y + 0.040 * s, z + 0.046),
               (x + sx * 0.080 * s, y + 0.084 * s, z + 0.040), 0.014 * s,
               0.012 * s, "木亮")
    B.beam("弩箭", (x, y - 0.070 * s, z + 0.048), (x, y + 0.120 * s, z + 0.048),
           0.008 * s, 0.008 * s, "铁暗")
    B.pyramid("箭镞", 0.020 * s, 0.018 * s, 0.026 * s, z + 0.035, "铁",
              at=(x, y + 0.126 * s), rotz=math.radians(90))


# ================================================================ 1★ 石塔 + 单面斗堡

def s1(B):
    """0.30 见方石塔 + 正面木斗堡 + 4 垛 + 一条长旗。

    "矮壮"的算法：塔身宽 0.30 / 净高 0.63 = 1:2.1。超过 1:2.5 就变烟囱。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.660, 0.660, at=(0.0, 0.0))
        akit.apron(B, 0.180, 0.090, G, "石暗", (0.0, 0.300))

    with B.group("塔基"):
        B.box("台座", 0.420, 0.420, 0.044, G, "台基", 0.008, at=(0.0, -0.020))
        akit.steps(B, 0.130, 2, G, G + 0.044, 0.198, 0.262, "台基")

    with B.group("塔身"):
        # 下段收分：底 0.34 → 上 0.30，塔就有了"根"
        B.box("塔脚", 0.340, 0.340, 0.110, G + 0.040, "石暗", 0.006, at=(0.0, -0.020))
        B.box("塔身", 0.300, 0.300, 0.500, G + 0.146, "石", 0.008, at=(0.0, -0.020))
        B.box("腰线", 0.322, 0.322, 0.012, G + 0.400, "石亮", 0.0, at=(0.0, -0.020))
        B.box("塔檐", 0.336, 0.336, 0.016, G + 0.634, "石暗", 0.0, at=(0.0, -0.020))
        B.box("塔台", 0.344, 0.344, 0.014, G + 0.650, "石", 0.0, at=(0.0, -0.020))
        B.roof_hip("塔顶", 0.300, 0.300, G + 0.660, G + 0.716, "瓦", 0.0,
                   (0.0, -0.020))
        akit.crenel_rect(B, "塔垛", 0.330, 0.330, G + 0.664, 1, 0.030, 0.036,
                         "石亮", at=(0.0, -0.020))

    with B.group("斗堡"):
        _hoarding(B, (0.0, 0.130), 0.276, G + 0.516, 0.112, 0.050, 3)
        _slit(B, 0.0, 0.130, G + 0.240)
        _slit(B, 0.0, -0.170, G + 0.300, axis="Y")
        _slit(B, 0.150, -0.020, G + 0.300, axis="X")
        akit.door(B, 0.0, 0.150, G + 0.048, 0.086, 0.130, role="木", frame="石亮",
                  detail=1)
        for s in (-1, 1):
            akit.shield(B, (s * 0.086, 0.150, G + 0.372), 0.040)

    with B.group("旗帜"):
        akit.wall_banner(B, (0.0, 0.156, G + 0.470), 0.104, 0.220)
        akit.wall_banner(B, (-0.148, -0.020, G + 0.420), 0.090, 0.190, axis="X")
        akit.wall_banner(B, (0.148, -0.020, G + 0.420), 0.090, 0.190, axis="X")
        akit.flag_pole(B, (-0.090, -0.100), G + 0.678, G + 0.848, 0.066, 0.056)

    with B.group("道具"):
        akit.barrel(B, (-0.238, 0.196), G)
        akit.crate(B, (0.240, 0.180), G, 0.056, 0.048)
        akit.rack(B, (0.246, -0.150), G, 0.104, 0.130, 2, True)


# ================================================================ 2★ 双耳斗堡

def s2(B):
    """加高 + 双耳斗堡（蓝锥顶）+ 腰线 + 城墙式台座。"""
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.760, 0.760, at=(0.0, 0.0))
        akit.apron(B, 0.220, 0.090, G, "石暗", (0.0, 0.336))
        for s in (-1, 1):
            akit.wall_low(B, 0.026, 0.240, G, 0.058, "石暗", "石",
                          at=(s * 0.330, 0.180))

    with B.group("塔基"):
        B.box("台座", 0.470, 0.470, 0.050, G, "台基", 0.008, at=(0.0, -0.020))
        akit.steps(B, 0.160, 2, G, G + 0.050, 0.216, 0.290, "台基")
        for s in (-1, 1):
            akit.buttress(B, (s * 0.150, 0.100), 0.050, 0.220, 0.044, sgn=2)

    with B.group("塔身"):
        B.box("塔脚", 0.390, 0.390, 0.120, G + 0.046, "石暗", 0.006, at=(0.0, -0.020))
        B.box("塔身", 0.340, 0.340, 0.560, G + 0.160, "石", 0.008, at=(0.0, -0.020))
        B.box("腰线", 0.362, 0.362, 0.014, G + 0.430, "石亮", 0.0, at=(0.0, -0.020))
        B.box("塔檐", 0.380, 0.380, 0.016, G + 0.714, "石暗", 0.0, at=(0.0, -0.020))
        B.box("塔台", 0.388, 0.388, 0.014, G + 0.730, "石", 0.0, at=(0.0, -0.020))
        B.roof_hip("塔顶", 0.344, 0.344, G + 0.740, G + 0.800, "瓦", 0.0,
                   (0.0, -0.020))
        akit.crenel_rect(B, "塔垛", 0.374, 0.374, G + 0.744, 1, 0.030, 0.038,
                         "石亮", at=(0.0, -0.020))

    with B.group("斗堡"):
        _hoarding(B, (0.0, 0.156), 0.300, G + 0.586, 0.116, 0.052, 3)
        for s in (-1, 1):
            # 双耳斗堡：两个小方斗挂在正面两角，各自一顶蓝锥 —— 箭塔的"耳朵"
            at = (s * 0.186, 0.128)
            B.box("耳堡%d" % s, 0.096, 0.110, 0.120, G + 0.500, "石", 0.0, at=at)
            B.box("耳托%d" % s, 0.108, 0.122, 0.014, G + 0.492, "石暗", 0.0, at=at)
            akit.pyramid_roof(B, "耳顶%d" % s, 0.090, 0.100, G + 0.624, 0.072,
                              at=at, role="瓦", cap="金", over=0.026)
        _slit(B, 0.0, 0.150, G + 0.300)
        _slit(B, 0.0, 0.150, G + 0.560)
        _slit(B, -0.170, -0.020, G + 0.360, axis="X")
        akit.door(B, 0.0, 0.150, G + 0.052, 0.094, 0.140, role="木", frame="石亮",
                  detail=2, studs=1)
        for s in (-1, 1):
            akit.shield(B, (s * 0.100, 0.152, G + 0.386), 0.042)

    with B.group("旗帜"):
        akit.wall_banner(B, (0.0, 0.156, G + 0.480), 0.116, 0.264)
        akit.wall_banner(B, (-0.168, -0.020, G + 0.460), 0.096, 0.200, axis="X")
        akit.wall_banner(B, (0.168, -0.020, G + 0.460), 0.096, 0.200, axis="X")
        akit.flag_pole(B, (-0.100, -0.100), G + 0.760, G + 1.000, 0.070, 0.060)

    with B.group("道具"):
        akit.barrel(B, (-0.280, 0.240), G)
        akit.crate(B, (0.286, 0.226), G, 0.058, 0.050)
        akit.rack(B, (-0.286, -0.120), G, 0.110, 0.140, 2, True)


# ================================================================ 3★ 四角小塔 + 弩炮

def s3(B):
    """厚塔 + 四角小塔（蓝锥顶）+ 出挑托石 + 弩炮。

    包络线：台座 0.14 → 塔身 0.86 → 垛口 0.96 → 角塔尖 1.06 → 弩炮 1.10 → 旗 1.38。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.860, 0.860, at=(0.0, 0.0))
        akit.apron(B, 0.260, 0.100, G, "石暗", (0.0, 0.386))
        for s in (-1, 1):
            akit.wall_low(B, 0.026, 0.280, G, 0.064, "石暗", "石",
                          at=(s * 0.386, 0.200))
        akit.wall_low(B, 0.300, 0.026, G, 0.064, "石暗", "石", at=(-0.240, 0.386))
        akit.wall_low(B, 0.300, 0.026, G, 0.064, "石暗", "石", at=(0.240, 0.386))

    with B.group("塔基"):
        B.box("台座", 0.540, 0.540, 0.056, G, "台基", 0.008, at=(0.0, -0.030))
        akit.steps(B, 0.190, 2, G, G + 0.056, 0.240, 0.320, "台基")

    with B.group("塔身"):
        B.box("塔脚", 0.460, 0.460, 0.140, G + 0.050, "石暗", 0.008, at=(0.0, -0.030))
        B.box("塔身", 0.400, 0.400, 0.660, G + 0.184, "石", 0.008, at=(0.0, -0.030))
        B.box("腰线1", 0.424, 0.424, 0.014, G + 0.360, "石亮", 0.0, at=(0.0, -0.030))
        # 出挑托石：一圈比塔身宽 5 cm 的暗石，垛口才有"压"的感觉
        B.box("托石", 0.470, 0.470, 0.024, G + 0.836, "石暗", 0.0, at=(0.0, -0.030))
        B.box("塔台", 0.462, 0.462, 0.016, G + 0.858, "石", 0.0, at=(0.0, -0.030))
        akit.crenel_rect(B, "塔垛", 0.444, 0.444, G + 0.874, 2, 0.030, 0.040,
                         "石亮", at=(0.0, -0.030))

    with B.group("角塔"):
        # 四角**外挑**小塔：坐在塔角外侧、带托石。放在垛口里面会变成
        # "平台上的四顶帽子"（v1 就这样），挑出来才是"角楼"。
        for sx in (-1, 1):
            for sy in (-1, 1):
                at = (sx * 0.222, -0.030 + sy * 0.222)
                B.box("小塔托%d%d" % (sx, sy), 0.128, 0.128, 0.018, G + 0.822,
                      "石暗", 0.0, at=at)
                B.box("小塔%d%d" % (sx, sy), 0.110, 0.110, 0.172, G + 0.832,
                      "石", 0.0, at=at)
                akit.pyramid_roof(B, "角顶%d%d" % (sx, sy), 0.122, 0.122,
                                  G + 1.006, 0.084, at=at, role="瓦", cap="金",
                                  over=0.028)

    with B.group("斗堡"):
        _hoarding(B, (0.0, 0.180), 0.300, G + 0.712, 0.116, 0.052, 2)
        for s in (-1, 1):
            _slit(B, s * 0.150, 0.186, G + 0.420, axis="X")
        _slit(B, 0.0, 0.186, G + 0.660)
        _slit(B, 0.0, -0.236, G + 0.500, axis="Y")
        akit.door(B, 0.0, 0.186, G + 0.058, 0.110, 0.160, role="木", frame="石亮",
                  detail=2, studs=1)
        for s in (-1, 1):
            akit.shield(B, (s * 0.124, 0.192, G + 0.372), 0.048)

    with B.group("弩炮"):
        _ballista(B, (0.0, -0.070), G + 0.890, 1.0)

    with B.group("旗帜"):
        akit.wall_banner(B, (0.0, 0.170, G + 0.610), 0.120, 0.276)
        akit.wall_banner(B, (-0.196, -0.030, G + 0.588), 0.100, 0.216, axis="X")
        akit.wall_banner(B, (0.196, -0.030, G + 0.588), 0.100, 0.216, axis="X")
        akit.flag_pole(B, (-0.140, -0.215), G + 1.084, G + 1.290, 0.074, 0.064)

    with B.group("道具"):
        akit.barrel(B, (-0.330, 0.300), G)
        akit.crate(B, (0.330, 0.290), G, 0.058, 0.050)
        akit.rack(B, (-0.330, -0.180), G, 0.110, 0.140, 2, True)


# ================================================================ 装配

def build(star, pal=None):
    B = akit.new(pal)
    {1: s1, 2: s2, 3: s3}[star](B)
    ob = B.join("箭塔_%d星" % star)
    return ob, B


