"""a_townhall.py —— 城镇大厅 · 三档（非塔类）

母题：**从市政厅到四方围合城堡**。
    1★ 半木构市政厅 + 短脊钟亭          占地 0.75  高 0.626
    2★ 石砌主城 Keep + 单角楼 + 门楼     占地 0.83  高 0.848
    3★ 四角塔围合城堡 + 中央大厅 + 金脊  占地 0.92  高 0.981

三条不动的线：
    · 高度只涨 0.22 / 0.13，**占地涨 0.08 / 0.09** —— 3★ 是"变宽变厚"，不是"变高变瘦"；
    · 屋顶语法三步走：厚檐双坡（1★）→ 双坡 + 竖脊门楼（2★）→ 主厅高坡 + 四塔垛口（3★）；
    · 市政身份四件：**钟面、拱门、蓝瓦、挂旗**。1★ 可以小，四件一件不能少。

面数账（1500 硬线 / 城镇大厅 3★ 放宽到 2000）：
    素盒 12 / 倒角盒 44 / 拱板 24 / 六边盾 20 / 瓦垄一道 12 / 门 detail0 24
"""
