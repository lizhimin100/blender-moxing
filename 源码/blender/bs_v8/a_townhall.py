# ================================================================ 1★ 市政厅

def s1(B):
    """单层半木构 + 厚蓝瓦顶 + 石阶小门廊 + 脊上矮钟亭。

    "钟亭不超过主体 1/3"：钟亭（含顶）0.104 m，主体 0.42 m → 25%。
    门廊顶必须**低于主檐 4 mm**：高过主檐的抱厦会读成"屋顶上又长了一个屋顶"。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.720, 0.690, at=(0.0, 0.010))
        akit.apron(B, 0.250, 0.110, G, "石暗", (0.0, 0.352))

    HW, HD, HY = 0.500, 0.350, -0.070
    YF = HY + HD / 2                      # 0.105 正面墙

    with B.group("主体"):
        B.box("石脚", HW + 0.030, HD + 0.030, 0.038, G, "石暗", 0.008, at=(0.0, HY))
        zt = akit.timber_wall(B, HW, HD, G + 0.036, 0.196, at=(0.0, HY),
                              studs=2, brace=True, rail=0.50)
        B.box("檐影", HW + 0.026, HD + 0.026, 0.011, zt - 0.002, "石暗", 0.0,
              at=(0.0, HY))
        B.box("檐口", HW + 0.034, HD + 0.034, 0.010, zt + 0.008, "石亮", 0.0,
              at=(0.0, HY))

    with B.group("门窗"):
        akit.door(B, 0.0, YF, G + 0.040, 0.096, 0.146, role="木", frame="木暗",
                  studs=1, trim="金", plate=True)
        for s in (-1, 1):
            akit.win(B, 0.040, 0.052,
                     (s * (HW / 2), HY + 0.010, G + 0.112), "洞", None, "X")

    with B.group("门廊"):
        # 台 → 两级台阶 → 两根石柱 → 竖脊门廊顶（竖脊+三角山花，横脊必读成雨棚）
        B.box("门廊台", 0.240, 0.196, 0.040, G, "台基", 0.006, at=(0.0, 0.192))
        akit.steps(B, 0.152, 2, G, G + 0.040, 0.290, 0.356, "台基")
        for s in (-1, 1):
            B.box("廊柱%d" % s, 0.030, 0.030, 0.152, G + 0.040, "石亮", 0.0,
                  at=(s * 0.092, 0.268))
            B.box("柱础%d" % s, 0.040, 0.040, 0.012, G + 0.040, "石暗", 0.0,
                  at=(s * 0.092, 0.268))
        akit.tiled_roof_y(B, 0.244, 0.196, G + 0.192, G + 0.274, at=(0.0, 0.196),
                          n=2, ridge="金", gable="灰泥", throat=0.014)

        # 钟面：市政身份。金圈 + 米白盘 + 两根深针（针必须画在盘外 6 mm）
        yf2 = 0.292
        B.disc("钟圈", 0.030, 0.010, (0.0, yf2, G + 0.234), "金", 8, "Y")
        B.disc("钟盘", 0.024, 0.009, (0.0, yf2 + 0.006, G + 0.234), "灰泥", 8, "Y")
        B.beam("钟针", (0.0, yf2 + 0.013, G + 0.234), (0.0, yf2 + 0.013, G + 0.249),
               0.0040, 0.0032, "洞")
        B.beam("钟针2", (0.0, yf2 + 0.013, G + 0.234), (0.011, yf2 + 0.013, G + 0.238),
               0.0034, 0.0028, "洞")

    with B.group("屋顶"):
        akit.tiled_roof(B, 0.604, 0.466, zt + 0.010, zt + 0.202, at=(0.0, HY),
                        n=4, ridge="木暗", gable="灰泥", gable_window=0.030)

    with B.group("钟亭"):
        zr = zt + 0.206
        B.box("亭座", 0.100, 0.078, 0.012, zr - 0.006, "石暗", 0.0, at=(0.0, HY))
        B.box("亭身", 0.092, 0.072, 0.044, zr + 0.006, "石亮", 0.0, at=(0.0, HY))
        for s in (-1, 1):
            B.plate("亭洞%d" % s, [(-0.020, 0.010), (0.020, 0.010), (0.020, 0.034),
                                  (-0.020, 0.034)], 0.008, "洞",
                    (0.0, HY + s * 0.037, zr), "Y")
        B.pyramid("亭顶", 0.098, 0.082, 0.038, zr + 0.050, "瓦", at=(0.0, HY))
        B.cyl("亭珠", 0.008, 0.012, zr + 0.086, 6, "金", at=(0.0, HY), r_top=0.010)

    with B.group("旗帜"):
        for s in (-1, 1):
            akit.wall_banner(B, (s * 0.204, YF + 0.003, G + 0.190), 0.052, 0.092)

    with B.group("道具"):
        bx, by = -0.286, 0.300
        for s in (-1, 1):
            B.box("告示柱%d" % s, 0.014, 0.014, 0.106, G, "木暗", 0.0,
                  at=(bx + s * 0.056, by))
        B.box("告示板", 0.136, 0.010, 0.060, G + 0.072, "布", 0.0, at=(bx, by))
        B.box("告示框", 0.146, 0.008, 0.010, G + 0.128, "木暗", 0.0, at=(bx, by))
        akit.barrel(B, (0.300, 0.318), G)
        akit.crate(B, (0.344, 0.226), G, 0.056, 0.048)
        for s in (-1, 1):
            B.box("灯柱%d" % s, 0.012, 0.012, 0.130, G, "木暗", 0.0,
                  at=(s * 0.196, 0.340))
            akit.lantern(B, (s * 0.196, 0.340), G + 0.130, 0.018)


# ================================================================ 2★ 主城 Keep

def s2(B):
    """石砌主城：L 型主体 + 后左角楼（锯齿垛口）+ 前凸门楼 + 两条长旗。

    1★→2★ 的三件事：**墙换石**（台基/墙裙/隅石）、**L 型加翼**（体量不再是一只盒子）、
    **竖向度交给角楼 + 旗桅**（不是把大厅拔高）。
    门楼顶是竖脊双坡：横脊会读成"雨棚"，竖脊才读"门楼"。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.800, 0.780, at=(0.0, 0.006))
        akit.apron(B, 0.300, 0.120, G, "石暗", (0.0, 0.372))
        B.box("甬道", 0.130, 0.220, 0.006, G, "石暗", 0.0, at=(0.0, 0.300))

    HW, HD, HY = 0.462, 0.336, -0.078

    with B.group("主厅"):
        zt = akit.stone_wall(B, HW, HD, G, 0.306, at=(0.0, HY), skirt=0.056)
        akit.tiled_roof(B, 0.570, 0.466, zt - 0.002, zt + 0.238, at=(0.0, HY),
                        n=3, ridge="石亮", gable="灰泥", barge_back=False)
        akit.win(B, 0.050, 0.064, (HW / 2, HY + 0.020, G + 0.150), "洞", None, "X")
        akit.shield(B, (HW / 2 + 0.006, HY - 0.036, G + 0.226), 0.030, "X")

    with B.group("翼楼"):
        # 右前翼：比主厅低一档，屋顶换四坡 —— 一眼看出"这是加的"，不是"拉长的"
        WW, WD, WX, WY = 0.212, 0.232, 0.246, 0.072
        zw = akit.stone_wall(B, WW, WD, G, 0.212, at=(WX, WY), skirt=0.050,
                             plinth_h=0.024, quoins=False)
        akit.hip_roof(B, "翼顶", WW + 0.086, WD + 0.086, zw - 0.004, zw + 0.132,
                      at=(WX, WY), role="瓦", ridge="金")
        akit.win(B, 0.044, 0.056, (WX + WW / 2, WY + 0.020, G + 0.126),
                 "洞", None, "X")
        akit.door(B, WX, WY + WD / 2, G + 0.026, 0.066, 0.100, role="木",
                  frame="石亮", detail=0)

    with B.group("角楼"):
        # **前左角**：2★ 的塔必须站在正立面这一侧。放在后角会被主屋顶整个吃掉，
        # 花 200 tri 买个看不见。0.185 见方 / 0.50 高 —— 宽高比 1:2.7，敦实。
        TX, TY2 = -0.300, 0.118
        top = akit.tower_sq(B, (TX, TY2), 0.185, 0.185, G, 0.500, cap="crenel",
                            merlon=1, at_name="角楼")
        akit.flag_pole(B, (TX, TY2), top - 0.012, G + 0.780, 0.070, 0.062)

    with B.group("门楼"):
        # 前凸门楼：石身 → 竖脊顶 → 拱门 → 钟面 → 长旗。
        # 竖向度在这里只到"门楼"，主厅高度不动 —— 一拔高就变钟塔。
        GX, GY, GW, GD = -0.072, 0.150, 0.244, 0.140
        YG = GY + GD / 2                   # 0.220
        B.box("门楼身", GW, GD, 0.352, G, "石暗", 0.008, at=(GX, GY))
        B.box("门楼裙", GW + 0.020, GD + 0.018, 0.050, G, "台基", 0.0, at=(GX, GY))
        B.box("门楼檐", GW + 0.030, GD + 0.026, 0.012, G + 0.350, "石亮", 0.0,
              at=(GX, GY))
        akit.arch_gate(B, (GX, YG), 0.112, 0.156, G + 0.050, ring=0.024)
        akit.tiled_roof_y(B, GW + 0.056, GD + 0.062, G + 0.356, G + 0.456,
                          at=(GX, GY + 0.004), n=1, ridge="金", gable="石亮",
                          throat=0.014)
        # 只留金圈 + 一根针：2★ 的钟面在 96 px 上是 6 px 的金环，
        # 米白盘在这个尺寸不加分，省 28 tri 给旗。
        B.disc("钟圈2", 0.026, 0.010, (GX, YG + 0.010, G + 0.404), "金", 8, "Y")
        B.beam("钟针2a", (GX, YG + 0.018, G + 0.404), (GX, YG + 0.018, G + 0.418),
               0.0040, 0.0030, "洞")
        akit.steps(B, 0.160, 2, G, G + 0.050, YG + 0.002, YG + 0.088, "台基")
        akit.wall_banner(B, (GX + 0.106, YG + 0.006, G + 0.320), 0.046, 0.110)

    with B.group("旗帜"):
        akit.banner_stand(B, (-0.318, 0.404), G, 0.238, 0.056, 0.086)
        akit.wall_banner(B, (0.231, -0.140, G + 0.300), 0.046, 0.086, axis="X")

    with B.group("道具"):
        akit.barrel(B, (-0.318, 0.238), G)
        akit.crate(B, (0.330, 0.322), G, 0.056, 0.048)


# ================================================================ 3★ 城堡

def s3(B):
    """四方围合城堡：四角塔 + 幕墙 + 中央大厅 + 门楼 + 金脊 + 狮鹫盾徽。

    包络线：幕墙 0.360 → 门楼 0.562 → 角塔 0.684 → 主厅脊 0.849。
    **金字塔，不是方尖碑。** 四塔只做垛口不做锥顶：锥顶×4 会立刻读成"四座礼拜堂"。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.920, 0.900, at=(0.0, 0.002))
        akit.apron(B, 0.300, 0.048, G, "石暗", (0.0, 0.440))
        B.box("甬道", 0.150, 0.200, 0.006, G, "石暗", 0.0, at=(0.0, 0.330))

    TX, TYW, TW = 0.320, 0.300, 0.190

    with B.group("四角塔"):
        for sx in (-1, 1):
            for sy in (-1, 1):
                at = (sx * TX, sy * TYW)
                # 3★ 四塔换**矮锥顶**（高 0.075 / 底宽 0.21 = 1:2.8，是炮塔不是尖塔）：
                # 锯齿垛口 ×4 在 96 px 上会连成一排白牙，矮锥顶才能把四角"钉"住，
                # 同时把队色从 12% 拉回 16% —— 队色下限是 11%，不能全靠一片屋顶。
                akit.tower_sq(B, at, TW, TW, G, 0.470, cap="pyramid",
                              cap_h=0.076, at_name="角塔%d%d" % (sx, sy))
                akit.win(B, 0.018, 0.046,
                         (at[0], sy * (TYW + TW / 2), G + 0.330),
                         "洞", None, "Y")

    with B.group("幕墙"):
        # 幕墙比塔身**深一档**（石暗）：一圈白的城墙会把四座塔糊成一块。
        # 前墙留门洞（±0.158），后墙整段，侧墙顶到塔心 —— 转角不靠碰运气。
        for sx in (-1, 1):
            akit.wall_low(B, 0.170, 0.070, G, 0.300, "石暗", "石",
                          at=(sx * 0.244, TYW))
            akit.crenel(B, "前垛%d" % sx, sx * 0.158, sx * 0.236, TYW,
                        G + 0.306, 2, 0.028, 0.030, 0.032)
            akit.wall_low(B, 0.070, 0.410, G, 0.300, "石暗", "石",
                          at=(sx * TX, 0.0))
        akit.wall_low(B, TX * 2 - TW + 0.020, 0.070, G, 0.300, "石暗", "石",
                      at=(0.0, -TYW))


    with B.group("主厅"):
        HW, HD, HY = 0.462, 0.412, -0.020
        zt = akit.stone_wall(B, HW, HD, G, 0.440, at=(0.0, HY), skirt=0.060)
        # 主厅四面被幕墙挡着，只在屋顶之上露出来；正立面留给门楼
        akit.tiled_roof(B, 0.552, 0.508, zt - 0.004, zt + 0.268, at=(0.0, HY),
                        n=4, ridge="金", gable="石亮")
        akit.win(B, 0.052, 0.070, (HW / 2, HY + 0.070, G + 0.330),
                 "洞", None, "X")
        akit.flag_pole(B, (0.0, HY), zt + 0.268, zt + 0.400, 0.090, 0.086)

    with B.group("门楼"):
        GX, GY, GW, GD = 0.0, 0.300, 0.316, 0.196
        YG = GY + GD / 2                   # 0.398
        B.box("门楼身", GW, GD, 0.460, G, "石暗", 0.008, at=(GX, GY))
        B.box("门楼裙", GW + 0.024, GD + 0.022, 0.056, G, "台基", 0.0, at=(GX, GY))
        B.box("门楼檐", GW + 0.036, GD + 0.030, 0.014, G + 0.458, "石亮", 0.0,
              at=(GX, GY))
        akit.arch_gate(B, (GX, YG), 0.132, 0.212, G + 0.056, ring=0.028,
                       doors=True)
        akit.portcullis(B, (GX, YG + 0.004), 0.116, 0.212, G + 0.058,
                        bars=3, rails=2)
        # 门楣上方：金边盾徽 + 两侧金翼（狮鹫的"翼"只做三级阶梯，不雕羽毛）
        akit.crest(B, (GX, YG + 0.006, G + 0.392), 0.150, 0.086, kind="shield")
        for s in (-1, 1):
            B.box("金翼%d" % s, 0.036, 0.014, 0.034, G + 0.404, "金", 0.0,
                  at=(GX + s * 0.098, YG + 0.004))
        akit.steps(B, 0.180, 2, G, G + 0.056, YG + 0.002, YG + 0.068, "台基")

    with B.group("旗帜"):
        akit.wall_banner(B, (0.140, YG + 0.006, G + 0.470), 0.050, 0.104)
        akit.wall_banner(B, (-0.140, YG + 0.006, G + 0.470), 0.050, 0.104)
        akit.banner_stand(B, (-0.392, 0.404), G, 0.226, 0.052, 0.080)

    with B.group("道具"):
        akit.barrel(B, (-0.384, 0.244), G)


# ================================================================ 装配

def build(star, pal=None):
    B = akit.new(pal)
    {1: s1, 2: s2, 3: s3}[star](B)
    ob = B.join("城镇大厅_%d星" % star)
    return ob, B


