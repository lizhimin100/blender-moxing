"""a_smith.py —— 铁匠铺 · 三档（非塔类）

母题：**敞棚 + 炉火 + 烟囱 + 铁砧**。
    1★ 三面墙敞棚（正面全开）+ 石炉膛 + 铁砧 + 水桶      占地 0.54  高 0.655
    2★ 石砌铺面 + 高石烟囱 + 侧挂敞棚工作间 + 磨石 + 武器架  占地 0.80  高 0.80
    3★ 更大石铺 + 两座烟囱 + 门前木披檐 + 金砧徽 + 铁锭堆    占地 0.88  高 0.955

三条不动的线：
    · **橙红炉口在任何一档都必须露在正面**：1★ 敞棚直接看得见；2★/3★ 把炉子
      搬进朝前的侧挂敞棚（铺面是封闭的石屋，炉火关在里面等于没有）；
    · 屋顶语法：1★ 竖脊敞棚（山墙朝前、前脸全开，两根粗柱）+ 2★/3★ 横脊厚檐石屋；
    · 高度靠**烟囱**涨，不靠拔高墙体：0.655 → 0.80 → 0.955。

面数账：素盒 12 / 倒角盒 44 / 三棱山墙 12 / 单坡披檐 60 / 门 detail2 84
"""
