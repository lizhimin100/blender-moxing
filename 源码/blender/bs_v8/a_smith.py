def s3(B):
    """更大石铺 + 两座烟囱 + 门前木披檐 + 金砧徽章 + 铁锭堆 + 挂旗。"""
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.880, 0.860, at=(0.0, 0.0))
        akit.apron(B, 0.220, 0.092, G, "石暗", (-0.060, 0.240))

    SX, SY, SW, SD = -0.080, -0.080, 0.470, 0.380
    YF = SY + SD / 2

    with B.group("铺面"):
        zt = akit.stone_wall(B, SW, SD, G, 0.336, at=(SX, SY), skirt=0.056)
        akit.tiled_roof(B, SW + 0.092, SD + 0.112, zt - 0.002, zt + 0.212,
                        at=(SX, SY), n=3, ridge="石亮", gable="灰泥",
                        barge_back=False)
        akit.door(B, SX, YF, G + 0.036, 0.096, 0.162, role="木", frame="石亮",
                  studs=1, trim="金", plate=True)
        akit.win(B, 0.044, 0.056, (SX + 0.156, YF + 0.001, G + 0.166),
                 "洞", "木暗", "Y")

    with B.group("烟囱"):
        # 截面 0.115（1:9.5 的细杆只读成旗杆）；两座都咬进后墙（y=-0.252）。
        # 主烟囱顶 0.951 —— 3★ 的总高靠砌体烟囱，不靠拔墙。
        stack(B, (-0.238, -0.252), 0.115, G, 0.860)
        stack(B, (0.062, -0.252), 0.105, G, 0.744)

    with B.group("徽章"):
        # 徽章直接上墙 —— 门楣到檐口之间有 0.15 的净空，够一块 0.07 高的牌。
        # 徽章钉在木披檐前檐上（招牌），不再贴墙 —— 檐口/披檐会把墙上的牌子吃掉
        akit.crest(B, (SX, YF + 0.106, G + 0.284), 0.132, 0.070, kind="anvil")

    with B.group("披檐"):
        # 门前**木**披檐（单坡 slab4）：蓝瓦只给主坡和工棚 —— 第三块蓝屋面
        # 会读成"堆屋顶"；木色小挑檐读成门头雨棚，同时保住"门前有遮檐"。
        B.slab4("门檐",
                [(SX - 0.132, YF - 0.004, G + 0.356),
                 (SX + 0.132, YF - 0.004, G + 0.356),
                 (SX + 0.132, YF + 0.108, G + 0.308),
                 (SX - 0.132, YF + 0.108, G + 0.308)], 0.024, "木")
        B.box("檐口木", 0.288, 0.022, 0.022, G + 0.292, "木暗", 0.0,
              at=(SX, YF + 0.100))
        for s in (-1, 1):
            B.beam("檐托%d" % s, (SX + s * 0.112, YF + 0.002, G + 0.300),
                   (SX + s * 0.112, YF + 0.070, G + 0.330), 0.016, 0.014,
                   "木暗")

    with B.group("工作间"):
        BX, BY, BW, BD = 0.318, -0.050, 0.250, 0.300
        B.box("棚地", BW, BD, 0.024, G, "台基", 0.0, at=(BX, BY))
        B.box("棚背墙", BW, 0.048, 0.240, G + 0.020, "石", 0.006,
              at=(BX, BY - BD / 2 + 0.024))
        for s in (-1, 1):
            B.box("棚柱%d" % s, 0.052, 0.052, 0.314, G + 0.020, "木暗", 0.0,
                  at=(BX + s * (BW / 2 - 0.030), BY + BD / 2 - 0.030))
        # 单坡顶的高边必须低于主屋**檐口**：原来高 32 mm，直接顶穿主屋面，
        # 渲染出来是一条斜着划过蓝瓦的黑线（读成裂缝）。
        pent_roof(B, (BX, BY + 0.006), BW + 0.026, BD + 0.064, G + 0.372,
                  G + 0.302, axis="Y", battens=3, name="工棚顶")
        akit.forge(B, (BX - 0.024, BY - 0.048), G + 0.024, 0.152, 0.126, 0.072)
        B.box("炉檐", 0.170, 0.026, 0.016, G + 0.024 + 0.114, "石亮", 0.0,
              at=(BX - 0.024, BY + 0.000))
        akit.anvil(B, (BX + 0.070, BY + 0.058), G + 0.024, 0.050)
        ingots(B, (BX + 0.020, BY + 0.120), G + 0.024, 3)

    with B.group("磨石"):
        akit.grindstone(B, (-0.352, 0.132), G, 0.040)

    with B.group("武器架"):
        akit.rack(B, (-0.356, -0.020), G, 0.120, 0.158, 2, True)

    with B.group("旗帜"):
        akit.wall_banner(B, (SX + 0.192, YF + 0.004, G + 0.300), 0.050, 0.096)

    with B.group("道具"):
        akit.barrel(B, (0.186, 0.186), G, 0.026, 0.058)
        akit.water_trough(B, (-0.190, 0.206), G, 0.096, 0.044, 0.032)


