def stack(B, at, w, z0, h, role="石", cap="石亮", taper=0.80):
    """石烟囱：下粗上细两段 + 压顶 + 烟口。

    烟口**压在压顶之上 4 mm** —— 同高会判共面（体检 ⑥）。
    """
    x, y = at
    B.box("烟囱下", w, w, h * 0.66, z0, role, 0.005, at=at)
    B.box("烟囱上", w * taper, w * taper, h * 0.34, z0 + h * 0.64, "石暗", 0.0,
          at=at)
    B.box("烟囱帽", w * 0.98, w * 0.98, 0.016, z0 + h * 0.98, cap, 0.0, at=at)
    B.box("烟口", w * 0.50, w * 0.50, 0.010, z0 + h * 0.98 + 0.010, "炭", 0.0,
          at=at)
    return z0 + h * 0.98 + 0.020


def pent_roof(B, at, w, d, z_hi, z_lo, axis="Y", role="瓦", fascia="木暗",
              battens=3, name="披檐"):
    """单坡披檐：一块厚板 + 几道瓦垄 + 檐口木。

    axis="Y"：高边在 −Y；axis="X"：高边在 −X。屋面用 slab4 直接给四点高度，
    所以"坡"是真的坡，不是把板子转个角度。
    """
    x, y = at
    if axis == "Y":
        y0, y1 = y - d / 2, y + d / 2
        B.slab4(name, [(x - w / 2, y0, z_hi), (x + w / 2, y0, z_hi),
                       (x + w / 2, y1, z_lo), (x - w / 2, y1, z_lo)], 0.022, role)
        for i in range(battens):
            t0 = 0.10 + 0.80 * i / battens
            t1 = t0 + 0.80 / battens * 0.84
            za = z_hi + (z_lo - z_hi) * t0 + 0.004
            zb = z_hi + (z_lo - z_hi) * t1 + 0.004
            B.slab4("%s瓦%d" % (name, i),
                    [(x - w / 2 + 0.012, y0 + d * t0, za),
                     (x + w / 2 - 0.012, y0 + d * t0, za),
                     (x + w / 2 - 0.012, y0 + d * t1, zb),
                     (x - w / 2 + 0.012, y0 + d * t1, zb)], 0.008,
                    "瓦暗" if i % 2 else "瓦")
        B.box(name + "檐", w + 0.012, 0.026, 0.026, z_lo - 0.020, fascia, 0.0,
              at=(x, y1 - 0.012))
    else:
        x0, x1 = x - d / 2, x + d / 2
        B.slab4(name, [(x0, y - w / 2, z_hi), (x0, y + w / 2, z_hi),
                       (x1, y + w / 2, z_lo), (x1, y - w / 2, z_lo)], 0.022, role)
        for i in range(battens):
            t0 = 0.10 + 0.80 * i / battens
            t1 = t0 + 0.80 / battens * 0.84
            za = z_hi + (z_lo - z_hi) * t0 + 0.004
            zb = z_hi + (z_lo - z_hi) * t1 + 0.004
            B.slab4("%s瓦%d" % (name, i),
                    [(x0 + d * t0, y - w / 2 + 0.012, za),
                     (x0 + d * t0, y + w / 2 - 0.012, za),
                     (x0 + d * t1, y + w / 2 - 0.012, zb),
                     (x0 + d * t1, y - w / 2 + 0.012, zb)], 0.008,
                    "瓦暗" if i % 2 else "瓦")
        B.box(name + "檐", 0.026, w + 0.012, 0.026, z_lo - 0.020, fascia, 0.0,
              at=(x1 - 0.012, y))


def open_gable_roof(B, at, w, d, z0, z1, gable="石", throat=0.020,
                    barge="木暗", battens=2):
    """竖脊敞棚顶：山墙朝 ±Y，**前脸不封**（只留博风板 + 脊），后面封山墙。

    前脸敞开的三角口就是铁匠铺的"取景框"：里面那团橙红炉火从任何角度都看得见。
    """
    x, y = at
    rise = z1 - z0
    B.roof_gable_y("棚顶", w, d, z0 - throat, z1, "瓦", at=at)
    # 后山墙
    pts = [(-w / 2 + 0.012, -throat - 0.004), (w / 2 - 0.012, -throat - 0.004),
           (0.0, rise - 0.012)]
    B.plate("棚后山", pts, 0.012, gable, (x, y - d / 2 + 0.004, z0), "Y")
    # 脊
    B.box("棚脊", 0.030, d + 0.008, 0.026, z1 - 0.014, barge, 0.0, at=at)
    # 前脸两根博风（Λ 形木框）
    for s in (-1, 1):
        B.beam("博风%d" % s, (x + s * (w / 2 - 0.010), y + d / 2 - 0.006,
                              z0 - throat), (x, y + d / 2 - 0.006, z1 - 0.008),
               0.024, 0.020, barge)
    # 瓦垄（前脸留空，垄只铺后半）
    for s in (-1, 1):
        for i in range(battens):
            t0 = 0.14 + 0.72 * i / battens
            t1 = t0 + 0.72 / battens * 0.82
            xa = x + s * (w / 2 - 0.006) * (1 - t0)
            xb = x + s * (w / 2 - 0.006) * (1 - t1)
            za = z0 + rise * t0 + 0.005
            zb = z0 + rise * t1 + 0.005
            B.slab4("棚瓦%d%d" % (s, i),
                    [(xa, y - d / 2 + 0.010, za), (xb, y - d / 2 + 0.010, zb),
                     (xb, y + d / 2 - 0.010, zb), (xa, y + d / 2 - 0.010, za)],
                    0.007, "瓦暗" if i % 2 else "瓦")
    return z1


def ingots(B, at, z, n=3):
    """铁锭堆：错位叠两层，冷铁亮面 —— 铁匠铺的量感。"""
    x, y = at
    for i in range(n):
        B.box("铁锭%d" % i, 0.056, 0.026, 0.018, z, "铁亮", 0.0,
              at=(x + (i - (n - 1) / 2) * 0.060, y))
    B.box("铁锭上", 0.056, 0.026, 0.018, z + 0.018, "铁", 0.0,
          at=(x + 0.030, y))


