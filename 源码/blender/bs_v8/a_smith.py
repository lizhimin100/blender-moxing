def s2(B):
    """石砌铺面（门 + 盾 + 高烟囱）+ 右侧敞棚工作间（炉火在这里）+ 磨石 + 武器架。"""
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.860, 0.800, at=(0.0, 0.0))
        akit.apron(B, 0.200, 0.090, G, "石暗", (-0.060, 0.212))

    SX, SY, SW, SD = -0.070, -0.060, 0.420, 0.340
    YF = SY + SD / 2

    with B.group("铺面"):
        zt = akit.stone_wall(B, SW, SD, G, 0.300, at=(SX, SY), skirt=0.050)
        akit.tiled_roof(B, SW + 0.086, SD + 0.106, zt - 0.002, zt + 0.196,
                        at=(SX, SY), n=3, ridge="石亮", gable="灰泥",
                        barge_back=False)
        akit.door(B, SX, YF, G + 0.034, 0.086, 0.146, role="木", frame="石亮",
                  studs=1, trim="金", plate=True)
        for s in (-1, 1):
            akit.win(B, 0.042, 0.052, (SX + s * 0.140, YF + 0.001, G + 0.150),
                     "洞", "木暗", "Y")
        akit.shield(B, (SX + SW / 2 + 0.006, SY + 0.024, G + 0.246), 0.034, "X")

    with B.group("烟囱"):
        stack(B, (SX + 0.168, SY - 0.090), 0.078, G, 0.690)

    with B.group("工作间"):
        BX, BY, BW, BD = 0.302, -0.020, 0.240, 0.280
        B.box("棚地", BW, BD, 0.024, G, "台基", 0.0, at=(BX, BY))
        B.box("棚背墙", BW, 0.048, 0.220, G + 0.020, "石", 0.006,
              at=(BX, BY - BD / 2 + 0.024))
        for s in (-1, 1):
            B.box("棚柱%d" % s, 0.050, 0.050, 0.290, G + 0.020, "木暗", 0.004,
                  at=(BX + s * (BW / 2 - 0.030), BY + BD / 2 - 0.030))
        pent_roof(B, (BX, BY + 0.006), BW + 0.050, BD + 0.060, G + 0.360,
                  G + 0.292, axis="Y", battens=3, name="工棚顶")
        akit.forge(B, (BX - 0.020, BY - 0.046), G + 0.024, 0.144, 0.118, 0.068)
        akit.anvil(B, (BX + 0.066, BY + 0.054), G + 0.024, 0.046)

    with B.group("磨石"):
        akit.grindstone(B, (-0.310, 0.148), G, 0.038)

    with B.group("武器架"):
        akit.rack(B, (-0.316, 0.010), G, 0.116, 0.150, 2, True)

    with B.group("道具"):
        akit.barrel(B, (0.196, 0.166), G, 0.026, 0.058)
        akit.water_trough(B, (-0.170, 0.196), G, 0.092, 0.042, 0.030)


