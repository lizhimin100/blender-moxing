def s1(B):
    """敞棚：三面墙 + 正面全开 + 两根粗柱 + 竖脊蓝瓦顶；炉膛靠后墙，铁砧居中。"""
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.700, 0.660, at=(0.0, -0.010))
        akit.apron(B, 0.176, 0.076, G, "石暗", (0.0, 0.242))

    with B.group("棚身"):
        B.box("棚地", 0.500, 0.440, 0.028, G, "台基", 0.006, at=(0.0, -0.020))
        z0 = G + 0.026
        B.box("后墙", 0.460, 0.060, 0.300, z0, "石", 0.008, at=(0.0, -0.190))
        for s in (-1, 1):
            B.box("侧墙%d" % s, 0.060, 0.260, 0.286, z0, "石", 0.008,
                  at=(s * 0.200, -0.050))
            B.box("檐口%d" % s, 0.076, 0.276, 0.012, z0 + 0.284, "石亮", 0.0,
                  at=(s * 0.200, -0.050))
            B.box("棚柱%d" % s, 0.058, 0.058, 0.330, z0, "木暗", 0.004,
                  at=(s * 0.196, 0.136))
            B.box("柱础%d" % s, 0.076, 0.076, 0.026, z0, "石暗", 0.0,
                  at=(s * 0.196, 0.136))
            B.beam("斜撑%d" % s, (s * 0.196, 0.136, z0 + 0.250),
                   (s * 0.196, 0.030, z0 + 0.300), 0.020, 0.018, "木暗")
        B.box("后墙檐", 0.348, 0.078, 0.012, z0 + 0.300, "石亮", 0.0,
              at=(0.0, -0.190))
        # 前楣：把两根棚柱连成"门框"，敞棚才读成工棚而不是凉亭
        B.box("前楣", 0.410, 0.052, 0.040, z0 + 0.300, "木暗", 0.0,
              at=(0.0, 0.136))

    with B.group("棚顶"):
        open_gable_roof(B, (0.0, -0.020), 0.564, 0.544, G + 0.322,
                        G + 0.548, gable="石", battens=2)

    with B.group("烟囱"):
        stack(B, (0.146, -0.176), 0.058, G, 0.560)

    with B.group("炉膛"):
        akit.forge(B, (0.000, -0.072), G + 0.028, 0.164, 0.130, 0.080)
        B.box("炉檐", 0.182, 0.028, 0.014, G + 0.028 + 0.118, "石亮", 0.0,
              at=(0.0, -0.022))

    with B.group("铁砧"):
        akit.anvil(B, (-0.108, 0.030), G + 0.028, 0.054)
        akit.stump(B, (-0.108, 0.102), G + 0.028, 0.036, 0.020)

    with B.group("道具"):
        akit.barrel(B, (0.156, 0.058), G + 0.028, 0.026, 0.056)
        akit.water_trough(B, (-0.150, 0.150), G + 0.028, 0.092, 0.044, 0.030)
        akit.pot(B, (0.086, 0.162), G + 0.028, 0.020, 0.028)
        akit.lantern(B, (0.196, 0.140), G + 0.212, 0.026)


