def s3(B):
    """宽石台 + 0.34 见方石塔身（0.80 高）+ 四角阶梯扶壁 + 挑石 + 锯齿垛口
    + **垛口之内的木构瞭望室**（八柱 + 栏杆 + 深色木地板）+ 矮四坡蓝瓦顶 + 大旗。

    上一版的问题：石塔顶上一块平板 + 一个锥顶 = 公交候车亭。
    这一版把"瞭望"做成**看得见的三件**：深色木地板（1.010–1.032）、
    八根望柱（到 1.132）、四道木栏杆（1.104）—— 屋面只做到 0.44 见方、
    出挑 0.05，柱顶到檐口 0.10 的净空保证 33° 相机看得到柱与栏杆。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.860, 0.780, at=(0.0, 0.006))
        akit.apron(B, 0.260, 0.090, G, "石暗", (0.0, 0.386))

    with B.group("石台"):
        B.box("石台", 0.720, 0.620, 0.086, G, "台基", 0.010, at=(0.0, -0.020))
        B.box("台帽", 0.744, 0.644, 0.014, G + 0.084, "石亮", 0.0, at=(0.0, -0.020))
        akit.steps(B, 0.220, 2, G, G + 0.098, 0.292, 0.392, "台基")
        for s in (-1, 1):
            B.box("台齿%d" % s, 0.060, 0.048, 0.030, G + 0.098, "石", 0.0,
                  at=(s * 0.300, -0.020 + 0.286))

    ZB = G + 0.098

    with B.group("塔身"):
        zt = _stone_shaft(B, (0.0, -0.020), 0.340, ZB, 0.800, "哨塔身")
        akit.door(B, 0.0, 0.152, ZB + 0.036, 0.074, 0.124, role="木", frame="石亮",
                  detail=0)
        for s in (-1, 1):
            B.plate("箭孔%d" % s, [(-0.011, 0.0), (0.011, 0.0), (0.011, 0.070),
                                  (-0.011, 0.070)], 0.010, "洞",
                    (s * 0.170, -0.020 + 0.030, ZB + 0.340), "X")
        B.plate("箭孔Y", [(-0.011, 0.0), (0.011, 0.0), (0.011, 0.056), (-0.011, 0.056)],
                0.010, "洞", (0.0, 0.152, ZB + 0.470), "Y")

    with B.group("扶壁"):
        for sx in (-1, 1):
            for sy in (-1, 1):
                _buttress2(B, (sx * 0.170, -0.020 + sy * 0.170), sx, sy,
                           w=0.070, z0=ZB, h=0.340, proj=0.058)

    with B.group("垛口"):
        # 挑石 → 垛台 → 一圈锯齿：垛口外沿 0.230，比屋面 0.220 还外 1 cm，
        # 所以锯齿永远是剪影上的一排牙，不会被屋檐吃掉。
        B.box("挑石", 0.408, 0.408, 0.020, zt - 0.030, "石暗", 0.0, at=(0.0, -0.020))
        B.box("垛台", 0.460, 0.460, 0.024, zt, "石", 0.0, at=(0.0, -0.020))
        akit.crenel_rect(B, "垛", 0.460, 0.460, zt + 0.024, 2, 0.028, 0.034,
                         "石亮", at=(0.0, -0.020))

    with B.group("瞭望室"):
        ZL = zt + 0.024                  # 垛台面
        B.box("望板", 0.400, 0.400, 0.022, ZL, "木暗", 0.0, at=(0.0, -0.020))
        ZF = ZL + 0.022                  # 望板面
        ZE = ZF + 0.100                  # 檐口
        for sx in (-1, 1):
            for sy in (-1, 1):
                B.box("望柱%d%d" % (sx, sy), 0.026, 0.026, ZE - ZF + 0.010, ZF,
                      "木", 0.0, at=(sx * 0.168, -0.020 + sy * 0.168))
                B.box("望柱中%d%d" % (sx, sy), 0.024, 0.024, ZE - ZF + 0.010, ZF,
                      "木", 0.0, at=(sx * 0.168, -0.020 + sy * 0.060))
                B.box("望柱中Y%d%d" % (sx, sy), 0.024, 0.024, ZE - ZF + 0.010, ZF,
                      "木", 0.0, at=(sx * 0.060, -0.020 + sy * 0.168))
        for s in (-1, 1):
            B.box("望栏X%d" % s, 0.336, 0.020, 0.020, ZF + 0.056, "木亮", 0.0,
                  at=(0.0, -0.020 + s * 0.168))
            B.box("望栏Y%d" % s, 0.020, 0.330, 0.017, ZF + 0.056, "木亮", 0.0,
                  at=(s * 0.168, -0.020))
            B.box("望栏下X%d" % s, 0.336, 0.016, 0.014, ZF + 0.020, "木", 0.0,
                  at=(0.0, -0.020 + s * 0.168))
            B.box("望栏下Y%d" % s, 0.016, 0.330, 0.011, ZF + 0.020, "木", 0.0,
                  at=(s * 0.168, -0.020))

    with B.group("屋顶"):
        _pyramid_roof(B, "哨顶", 0.440, 0.440, ZE, 0.150, at=(0.0, -0.020), rows=2,
                      eave="瓦暗")
        akit.flag_pole(B, (0.0, -0.020), ZE + 0.138, 1.360, 0.120, 0.092)

    with B.group("旗帜"):
        akit.wall_banner(B, (0.0, 0.152, ZB + 0.470), 0.052, 0.150)
        akit.wall_banner(B, (0.172, -0.020, ZB + 0.470), 0.052, 0.150, axis="X")
        akit.wall_banner(B, (0.0, -0.192, ZB + 0.470), 0.052, 0.150)
        akit.wall_banner(B, (-0.172, -0.020, ZB + 0.470), 0.052, 0.150, axis="X")

    with B.group("道具"):
        B.box("柴堆", 0.160, 0.052, 0.034, G, "木", 0.0, at=(-0.300, 0.244))
        B.box("柴堆2", 0.136, 0.048, 0.028, G + 0.034, "木亮", 0.0, at=(-0.300, 0.244))
        akit.barrel(B, (0.300, 0.250), G, 0.026, 0.056)


# ================================================================ 装配

def build(star, pal=None):
    B = akit.new(pal)
    {1: s1, 2: s2, 3: s3}[star](B)
    ob = B.join("哨塔_%d星" % star)
    return ob, B


