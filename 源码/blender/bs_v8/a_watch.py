def s2(B):
    """石砌塔身（隅石 + 腰线）+ 木构瞭望室 + 出挑木平台 + 蓝方锥顶 + 旗。

    返工要点：望柱顶到檐口（0.812），栏杆顶 0.736 —— 檐口比栏杆高 0.062、
    出挑只有 0.030，3/4 视一定看得见栏杆和望柱。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.720, 0.700, at=(0.0, 0.008))
        akit.apron(B, 0.190, 0.086, G, "石暗", (0.0, 0.356))
        B.box("石阶", 0.300, 0.150, 0.028, G, "台基", 0.0, at=(0.0, 0.284))

    with B.group("石塔身"):
        zt = _stone_shaft(B, (0.0, -0.020), 0.280, G + 0.022, 0.500, "塔身")
        akit.door(B, 0.0, -0.020 + 0.142, G + 0.040, 0.064, 0.104,
                  role="木", frame="石亮", detail=0)
        akit.win(B, 0.020, 0.052, (0.0, -0.020 + 0.142, G + 0.330), "洞", None, "Y")

    zp = zt + 0.014
    ZE = 0.812
    with B.group("瞭望室"):
        for s in (-1, 1):
            B.box("挑梁X%d" % s, 0.420, 0.036, 0.026, zt + 0.002, "木暗", 0.0,
                  at=(0.0, -0.020 + s * 0.120))
            B.box("挑梁Y%d" % s, 0.036, 0.400, 0.021, zt + 0.002, "木暗", 0.0,
                  at=(s * 0.120, -0.020))
        B.box("望台", 0.420, 0.420, 0.026, zp, "木亮", 0.006, at=(0.0, -0.020))
        for sx in (-1, 1):
            for sy in (-1, 1):
                B.box("望柱%d%d" % (sx, sy), 0.038, 0.038, ZE - zp - 0.022,
                      zp + 0.022, "木暗", 0.0, at=(sx * 0.168, -0.020 + sy * 0.168))
        B.box("望壁X", 0.300, 0.024, 0.146, zp + 0.030, "木", 0.0,
              at=(0.0, -0.020 - 0.156))
        B.box("望壁Y", 0.024, 0.300, 0.140, zp + 0.030, "木", 0.0,
              at=(-0.156, -0.020))
        for s in (-1, 1):
            B.box("望栏X%d" % s, 0.372, 0.022, 0.022, zp + 0.090, "木亮", 0.0,
                  at=(0.0, -0.020 + s * 0.168))
            B.box("望栏Y%d" % s, 0.022, 0.360, 0.018, zp + 0.090, "木亮", 0.0,
                  at=(s * 0.168, -0.020))

    with B.group("屋顶"):
        _pyramid_roof(B, "哨顶", 0.480, 0.480, ZE, 0.190, at=(0.0, -0.020), rows=2)
        for s in (-1, 1):
            B.beam("撑木X%d" % s, (s * 0.168, -0.020 + 0.160, ZE - 0.012),
                   (s * 0.196, -0.020 + 0.126, ZE + 0.044), 0.018, 0.016, "木暗")
            B.beam("撑木Y%d" % s, (0.160, -0.020 + s * 0.168, ZE - 0.012),
                   (0.126, -0.020 + s * 0.196, ZE + 0.044), 0.018, 0.016, "木暗")

    with B.group("梯子"):
        akit.ladder(B, (0.194, -0.020), G + 0.030, zp + 0.012, 0.030, 6)

    with B.group("旗帜"):
        akit.flag_pole(B, (0.0, -0.020), ZE + 0.178, 1.160, 0.086, 0.082)
        akit.wall_banner(B, (0.0, 0.156, zp + 0.094), 0.046, 0.092)
        akit.wall_banner(B, (0.172, -0.020, zp + 0.094), 0.046, 0.092, axis="X")

    with B.group("道具"):
        B.box("柴堆", 0.140, 0.050, 0.032, G, "木", 0.0, at=(0.252, 0.246))
        B.box("柴堆2", 0.120, 0.046, 0.028, G + 0.032, "木亮", 0.0, at=(0.252, 0.246))


