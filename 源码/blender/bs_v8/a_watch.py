# ================================================================ 局部零件

def _pyramid_roof(B, name, w, d, z0, h, at=(0.0, 0.0), rows=2, eave="木暗",
                  role="瓦", dark="瓦暗", cap="金", ring=True):
    """蓝方锥顶 + 叠瓦 + 金顶珠。

    瓦垄是**贴着坡面外推 4 mm 的梯形板**，四点必须按环序给（v1 给成对角序，
    slab4 拉出两个交叉三角，屋面上出现一道从脊到角的斜缝）。
    """
    x, y = at
    if ring:
        B.box(name + "檐", w + 0.024, d + 0.024, 0.016, z0 - 0.014, eave, 0.0, at=at)
    B.pyramid(name, w, d, h, z0, role, at=at)
    for s in (-1, 1):
        L = math.hypot(d / 2, h)
        ny, nz = s * h / L, (d / 2) / L
        for i in range(rows):
            t0, t1 = i * 0.90 / rows, (i + 1) * 0.90 / rows
            off = 0.004 + i * 0.0012
            P = [(x + u * w / 2 * (1 - t), y + s * d / 2 * (1 - t) + ny * off,
                  z0 + t * h + nz * off) for t, u in ((t0, -1), (t1, -1), (t1, 1), (t0, 1))]
            B.slab4("%s瓦Y%d%d" % (name, s, i), P, 0.006, dark if i % 2 else role)
        L = math.hypot(w / 2, h)
        nx, nz = s * h / L, (w / 2) / L
        for i in range(rows):
            t0, t1 = i * 0.90 / rows, (i + 1) * 0.90 / rows
            off = 0.004 + i * 0.0012
            P = [(x + s * w / 2 * (1 - t) + nx * off, y + u * d / 2 * (1 - t),
                  z0 + t * h + nz * off) for t, u in ((t0, -1), (t0, 1), (t1, 1), (t1, -1))]
            B.slab4("%s瓦X%d%d" % (name, s, i), P, 0.006, dark if i % 2 else role)
    B.cyl(name + "珠", 0.009, 0.016, z0 + h - 0.006, 6, cap, at=at, r_top=0.011)


def _stone_shaft(B, at, w, z0, h, name="塔身", quoins=2):
    """石塔身：塔基 → 身 → 腰线 → 隅石（正面两角）。**基与身不同高**，不共面。"""
    x, y = at
    B.box(name + "基", w + 0.036, w + 0.036, 0.030, z0, "石暗", 0.0, at=at)
    B.box(name, w, w, h - 0.024, z0 + 0.024, "石", 0.008, at=at)
    B.box(name + "腰", w + 0.018, w + 0.018, 0.012, z0 + h * 0.60, "石亮", 0.0, at=at)
    for s in (-1, 1):
        for k in range(quoins):
            B.box("%s隅%d%d" % (name, s, k), 0.040, 0.040, 0.058,
                  z0 + 0.034 + k * 0.094, "石亮", 0.0,
                  at=(x + s * (w / 2 - 0.016), y + w / 2 - 0.018))
    return z0 + h


def _buttress2(B, at, sx, sy, w=0.070, z0=G, h=0.300, proj=0.056, role="石",
               cap="石亮"):
    """阶梯扶壁（两段 + 斜帽）。akit.buttress 的帽件参数串位会 KeyError，
    这里按同一造型重写：外段矮、内段高，帽比身宽 4 mm。"""
    x, y = at
    for i in range(2):
        k = 1.0 - i * 0.36
        d = proj * k
        hh = h * (1.0 - i * 0.32)
        B.box("扶壁%d%d%d" % (sx, sy, i), w, d + 0.008, hh, z0, role, 0.0,
              at=(x + sx * (w / 2 - 0.012), y + sy * (d / 2 - 0.004)))
        B.box("扶壁帽%d%d%d" % (sx, sy, i), w * 0.94, d * 0.92, 0.014, z0 + hh,
              cap, 0.0, at=(x + sx * (w / 2 - 0.014), y + sy * (d / 2 - 0.006)))


# ================================================================ 1★ 木构瞭望塔

def s1(B):
    """四根外撇木腿 + 两道横箍 + 斜撑 + 梯子 + 架空平台 + 栏杆 + 四柱蓝方锥顶 + 旗。

    返工要点：**屋顶出挑收到 0.026、檐口抬到栏杆之上 0.05，靠四根短柱撑住**。
    上一版 0.05 出挑 + 0.16 净空，33° 相机正好被檐口切掉整圈栏杆，
    平台就退化成一顶蓝帽子下面的黑缝。
    """
    B.base()
    with B.group("场地"):
        akit.yard(B, 0.640, 0.620, at=(0.0, 0.010))
        akit.apron(B, 0.170, 0.080, G, "石暗", (0.0, 0.330))

    LB, LT = 0.236, 0.150
    ZT = 0.545
    ZE = 0.706                       # 檐口（四根短柱顶）

    with B.group("塔腿"):
        for sx in (-1, 1):
            for sy in (-1, 1):
                B.box("腿脚%d%d" % (sx, sy), 0.082, 0.082, 0.020, G, "石暗", 0.0,
                      at=(sx * LB, sy * LB))
                B.beam("木腿%d%d" % (sx, sy),
                       (sx * LB, sy * LB, G + 0.008),
                       (sx * LT, sy * LT, ZT + 0.006), 0.052, 0.052, "木")
        for k, zz in ((0, G + 0.128), (1, G + 0.280)):
            t = (zz - G) / (ZT - G)
            hw = LB + (LT - LB) * t
            for s in (-1, 1):
                B.box("横箍X%d%d" % (k, s), 2 * hw + 0.024, 0.030, 0.034, zz,
                      "木暗", 0.0, at=(0.0, s * hw))
                B.box("横箍Y%d%d" % (k, s), 0.030, 2 * hw + 0.018, 0.029, zz,
                      "木暗", 0.0, at=(s * hw, 0.0))
        for s in (-1, 1):
            B.beam("斜撑X%d" % s, (-s * 0.212, 0.216, G + 0.024),
                   (s * 0.160, 0.170, G + 0.290), 0.024, 0.020, "木暗")
            B.beam("斜撑Y%d" % s, (0.216, -s * 0.212, G + 0.024),
                   (0.170, s * 0.160, G + 0.290), 0.024, 0.020, "木暗")

    with B.group("平台"):
        B.box("台面", 0.440, 0.440, 0.028, ZT, "木亮", 0.006)
        for s in (-1, 1):
            B.box("托梁%d" % s, 0.400, 0.032, 0.030, ZT - 0.030, "木暗", 0.0,
                  at=(0.0, s * 0.150))
        # 四根短柱：从平台面直顶到檐口，比栏杆高 0.07 —— 屋面不靠栏杆承重
        for sx in (-1, 1):
            for sy in (-1, 1):
                B.box("角柱%d%d" % (sx, sy), 0.034, 0.034, ZE - ZT - 0.024,
                      ZT + 0.024, "木", 0.0, at=(sx * 0.176, sy * 0.176))
        for s in (-1, 1):
            B.box("栏杆X%d" % s, 0.380, 0.024, 0.024, ZT + 0.071, "木亮", 0.0,
                  at=(0.0, s * 0.176))
            B.box("栏杆X中%d" % s, 0.380, 0.017, 0.016, ZT + 0.030, "木", 0.0,
                  at=(0.0, s * 0.176))
            B.box("栏杆Y%d" % s, 0.024, 0.372, 0.020, ZT + 0.071, "木亮", 0.0,
                  at=(s * 0.176, 0.0))
            B.box("栏杆Y中%d" % s, 0.017, 0.372, 0.013, ZT + 0.030, "木", 0.0,
                  at=(s * 0.176, 0.0))

    with B.group("梯子"):
        akit.ladder(B, (0.198, 0.040), G + 0.006, ZT + 0.012, 0.032, 5)

    with B.group("屋顶"):
        _pyramid_roof(B, "哨顶", 0.492, 0.492, ZE, 0.196, at=(0.0, 0.0), rows=2)

    with B.group("旗帜"):
        akit.flag_pole(B, (0.0, 0.0), ZE + 0.186, 1.020, 0.090, 0.078)
        akit.wall_banner(B, (0.0, 0.190, ZT + 0.086), 0.050, 0.082)
        akit.wall_banner(B, (0.190, 0.0, ZT + 0.086), 0.050, 0.082, axis="X")

    with B.group("道具"):
        B.box("柴堆", 0.140, 0.048, 0.030, G, "木", 0.0, at=(-0.238, 0.248))
        B.box("柴堆2", 0.118, 0.044, 0.026, G + 0.030, "木亮", 0.0, at=(-0.238, 0.248))


