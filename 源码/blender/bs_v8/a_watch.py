"""a_watch.py —— 哨塔 · 三档（塔类）

母题：**木构瞭望塔 → 石基混合 → 全石哨塔**。
    1★ 木构瞭望塔：四根外撇木腿 + 两道横箍 + 梯子 + 带栏杆的架空平台 + 四柱蓝方锥顶 + 旗
       占地 0.64  高 1.02
    2★ 石砌塔身（0.28 见方、隅石、腰线）+ 上段木构瞭望室 + 出挑木平台 + 蓝方锥顶 + 旗
       占地 0.72  高 1.16
    3★ 全石塔：0.34 见方塔身 + 四角阶梯扶壁 + 挑石 + 锯齿垛口 + 蓝矮锥顶 + 箭孔 + 大旗
       占地 0.86  高 1.36

哨塔与箭塔的分界：**哨塔偏木、偏瘦、必须有开放式瞭望平台**；
箭塔是全石、矮壮、有弩炮。所以 1★ 整座架空，2★ 上层是敞廊，3★ 才收成石塔。

三条不动的线：
    · 高度 1.02 / 1.16 / 1.36，**占地 0.64 / 0.72 / 0.86**；
    · 语法：全木架空 → 石脚下木上身 → 全石 + 扶壁 + 垛口；
    · 识别件：**外撇木腿 + 能看穿的平台 + 蓝方锥顶**（3★ 换成垛口环 + 锥顶）。

屋面纪律：檐口必须比栏杆高 7 cm 以上、出挑不超过 5 cm ——
否则从 33° 的相机看下去，整圈栏杆会被屋檐吃掉（v1 的坑）。
"""
