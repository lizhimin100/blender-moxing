def _s1(B):
    """1★：单一体量石厅 + 脊上钟亭。

    识别度四件套：蓝瓦顶（队色）/ 拱门 / 钟面 / 一对挂旗。
    比 v1 少了烟囱与披屋 —— 那两件是"农舍"的语法，一件都不能留。
    """
    PL = 0.110
    W1, D1 = 0.520, 0.410
    H1 = 0.252
    Z1 = PL + H1                     # 0.362
    YF = D1 / 2

    B.plinth(0.900, 0.760, 0.030, Z0, "台基", 0.007)
    B.box("大厅", W1, D1, H1, PL, "石", 0.010)
    B.box("墙裙", W1 + 0.024, D1 + 0.024, 0.062, PL, "石暗", 0.006)
    B.cornice("腰线", W1 + 0.024, D1 + 0.024, PL + 0.062, grow=0.012, h=0.009)
    B.quoin("隅石", W1 + 0.024, D1 + 0.024, PL, 0.068, t=0.038)
    B.steps(0.198, 3, Z0, PL, 0.380, 0.474, "石")

    portal(B, YF, PL, 0.132, 0.206, 0.042, 0.030)

    # 屋面（脊沿 X，山墙朝 ±X）
    RW, RD, ZR = W1, D1 + 0.052, 0.574
    rise = ZR - Z1
    B.roof_tiled("主屋顶", RW, RD, Z1, ZR, "瓦", n=4, throat=0.013)
    for s in (-1, 1):
        gable_end(B, s * (W1 / 2), RD, Z1, rise, "灰泥", 0.012, 0.010,
                  window=(0.040, 0.046, Z1 + 0.050))
        gx = s * (W1 / 2 + 0.010)
        B.box("山墙横枋%d" % s, 0.010, RD - 0.070, 0.010, Z1 + 0.030, "木暗", 0.0,
              at=(gx, 0.0))
        barge(B, s * (W1 / 2), RD, Z1, rise, "木暗", 0.014, 0.010, 1 if s > 0 else -1)
    ridge_cap(B, RW, RD, ZR, rise)

    clock_cote(B, 0.505, 0.650, 0.098, 0.596, 0.050, 0.122)

    banner_pair(B, YF, 0.298, 0.196, 0.062, 0.106, 0.018)
    notice_board(B, PL, (-0.306, 0.292))
    for s in (-1, 1):
        B.lantern("壁灯%d" % s, (s * 0.134, YF), 0.212, bracket=0.024, drop=0.026)

    for s in (-1, 1):
        B.window("侧窗%d" % s, 0.042, 0.062, (s * (W1 / 2 + 0.006), 0.020, PL + 0.092),
                 "窗", True, "石亮", "X")


