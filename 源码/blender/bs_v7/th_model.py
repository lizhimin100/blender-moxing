def portal(B, y_face, z0, w_open=0.132, h_open=0.206, jamb=0.040, depth=0.030):
    """拱门：两根石门柱 + 拱券 + 双扇木门 + 金门环。

    深度靠门柱凸出 3 cm 的阴影给，不做真开洞 —— 1 m 尺度上真开洞要多花 100 tri，
    俯视角还看不见。门柱顶加一块拱脚石，让拱券有落点。
    """
    r = w_open / 2.0
    for s in (-1, 1):
        B.box("门柱%d" % s, jamb, depth, h_open, z0, "石", 0.0,
              at=(s * (r + jamb / 2), y_face + depth / 2))
        B.box("拱脚%d" % s, jamb + 0.012, depth + 0.010, 0.014, z0 + h_open,
              "石亮", 0.0, at=(s * (r + jamb / 2), y_face + depth / 2 + 0.005))
    B.arch_plate("拱券", w_open + jamb * 2, h_open + jamb * 0.95, depth * 0.60, "石亮",
                 (0.0, y_face + depth * 0.22, z0), 7)
    B.arch_plate("门洞", w_open * 0.97, h_open * 0.99, 0.012, "窗",
                 (0.0, y_face + 0.008, z0), 7)
    dw = w_open * 0.94
    for i, off in enumerate((-dw / 4.0, dw / 4.0)):
        B.box("门扇%d" % i, dw / 2 - 0.004, 0.014, h_open * 0.66, z0, "木", 0.0,
              at=(off, y_face + 0.017))
        B.box("门板%d" % i, dw / 2 - 0.014, 0.005, h_open * 0.52, z0 + h_open * 0.06,
              "木暗", 0.0, at=(off, y_face + 0.025))
    B.box("门环", 0.010, 0.006, 0.010, z0 + h_open * 0.34, "金", 0.0,
          at=(dw * 0.17, y_face + 0.028))


def gable_end(B, x, d, z1, rise, role="灰泥", thick=0.012, inset=0.010,
              window=None):
    """山墙：三角薄板盖住屋顶端面（端面埋在板里，不共面）。

    window=(w,h,z) 加一扇山花窗 —— 山墙是 3/4 机位里第二大的面，空着就白瞎了。
    """
    pts = [(-d / 2 + inset, -0.008), (d / 2 - inset, -0.008), (0.0, rise - 0.018)]
    sgn = 1 if x > 0 else -1
    B.plate("山墙%d" % sgn, pts, thick, role, (x, 0.0, z1), "X")
    if window:
        w, h, z = window
        B.plate("山花窗%d" % sgn, [(-w / 2, 0.0), (w / 2, 0.0), (w / 2, h), (-w / 2, h)],
                0.009, "窗", (x + sgn * (thick / 2 + 0.001), 0.0, z), "X")


def barge(B, x, d, z1, rise, role="木暗", w=0.014, t=0.010, sgn=1):
    """博风板：沿山墙斜边走两根方料，比山墙面再凸 4 mm —— "屋檐出挑"的替身。"""
    xx = x + sgn * 0.011
    for s in (-1, 1):
        B.beam("博风%s%d" % (sgn, s), (xx, s * (d / 2 - 0.006), z1 - 0.006),
               (xx, 0.0, z1 + rise - 0.012), w, t, role)


def clock_cote(B, z_base, z_top, w, clock_z, cap_h, cap_w, y=-0.004,
               pennant=True, louver=True):
    """钟亭：塔身（埋进屋面）→ 钟面 → 檐口 → 蓝方锥 → 金顶饰 → 三角旗。

    比例死线：cap_h / cap_w >= 0.42，1.2 以下读成"戴帽子的烟囱"。
    """
    B.box("钟亭身", w, w, z_top - z_base, z_base, "石亮", 0.006, at=(0.0, y))
    B.clock("钟面", w * 0.335, (0.0, y + w / 2 + 0.002, clock_z), "Y")
    if louver:
        for s in (-1, 1):
            B.window("钟亭侧窗%d" % s, 0.028, 0.042,
                     (s * (w / 2 + 0.005), y, clock_z - 0.024), "窗", False, axis="X")
        B.window("钟亭后窗", 0.028, 0.042, (0.0, y - w / 2 - 0.005, clock_z - 0.024),
                 "窗", False, axis="Y")
    B.cornice("钟亭檐", w, w, z_top, (0.0, y), grow=0.020, h=0.010)
    zc = z_top + 0.018
    B.pyramid("钟亭顶", cap_w, cap_w, cap_h, zc, "瓦", at=(0.0, y), bevel=0.0)
    za = zc + cap_h
    B.cyl("顶饰座", 0.011, 0.010, za - 0.004, 6, "金", at=(0.0, y), r_top=0.013)
    B.cone("顶饰", 0.013, 0.020, za + 0.006, 6, "金", at=(0.0, y))
    if pennant:
        B.flag("亭旗", za + 0.026, h=0.028, at=(0.0, y), L=0.040, H=0.026)


def notice_board(B, base_z, at, w=0.072, h=0.050, pennant=True):
    """公告板：两柱 + 深色背板 + 浅色板面 + 两张告示。市政身份的第二件小物。"""
    x, y = at
    for s in (-1, 1):
        B.box("告示柱%d" % s, 0.009, 0.009, 0.056, base_z, "木暗", 0.0,
              at=(x + s * (w / 2 - 0.008), y))
    B.box("告示背板", w + 0.010, 0.010, h + 0.008, base_z + 0.050, "木暗", 0.0, at=(x, y))
    B.box("告示板面", w, 0.008, h, base_z + 0.054, "木亮", 0.0, at=(x, y + 0.006))
    for i, (ox, oz, ww) in enumerate(((-0.014, 0.062, 0.026), (0.014, 0.060, 0.024))):
        B.box("告示%d" % i, ww, 0.004, 0.030 if i == 0 else 0.026, base_z + oz, "灰泥",
              0.0, at=(x + ox, y + 0.010))
    if pennant:
        B.cyl("告示柱顶", 0.005, 0.022, base_z + 0.056, 5, "金",
              at=(x - w / 2 + 0.008, y))
        B.plate("告示旗", [(0.0, 0.0), (0.026, -0.008), (0.0, -0.016)], 0.004, "旗",
                (x - w / 2 + 0.008, y + 0.002, base_z + 0.076), "Y")


def ridge_cap(B, RW, RD, ZR, rise, role="金", d=0.040, lift=0.009, ends=False):
    """屋脊压顶：**跟屋面同坡**的小三棱柱，不是一根方条。

    方条在 45° 屋面上必然两端翘起 —— 它的底边是水平的，屋面在往下走，
    差出来的三角就是那道"悬空金条"的缝。压顶只有做成同坡的薄壳才贴得住。
    """
    slope = rise / (RD / 2)
    B.roof_gable("金脊", RW + 0.004, d, ZR + lift - slope * d / 2, ZR + lift,
                 role, 0.0, fascia=False)
    if ends:
        for s in (-1, 1):
            B.box("脊端%d" % s, 0.024, 0.040, 0.018, ZR + lift - 0.020, role, 0.0,
                  at=(s * (RW / 2 - 0.014), 0.0))


def banner_pair(B, y_face, z, x, w=0.066, h=0.116, reach=0.020):
    """一对挂旗：金杆挑出墙面 + 横担 + 旗面 + 底边金翻边。"""
    for s in (-1, 1):
        B.beam("旗挑%d" % s, (s * x, y_face - 0.004, z + 0.006),
               (s * x, y_face + reach, z + 0.006), 0.009, 0.007, "金")
        B.beam("旗杆%d" % s, (s * x - w / 2, y_face + reach - 0.002, z + 0.002),
               (s * x + w / 2, y_face + reach - 0.002, z + 0.002), 0.008, 0.006, "金")
        B.banner("挂旗%d" % s, w, h, (s * x, y_face + reach - 0.004, z), "旗", "金", "Y")


