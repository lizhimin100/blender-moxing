def build(star=3, name=None, pal=None):
    B = mkit.B(pal=pal)
    B.base()
    {1: _s1, 2: _s2, 3: _s3}[star](B)
    nm = name or ("城镇大厅_%d星" % star)
    ob = B.join(nm)
    ob["star"] = star
    ob["palette"] = (pal if isinstance(pal, str) else mkit.DEFAULT_PALETTE)
    ob.data.calc_loop_triangles()
    return ob, B


def stats(ob, B):
    lo, hi = B.bbox()
    return {
        "name": ob.name,
        "tris": len(ob.data.loop_triangles),
        "verts": len(ob.data.vertices),
        "size": [round(hi[i] - lo[i], 4) for i in range(3)],
        "min": [round(lo[i], 5) for i in range(3)],
        "max": [round(hi[i], 5) for i in range(3)],
        "materials": [m.name for m in ob.data.materials],
        "team_area": round(B.team_area() * 100, 2),
        "soft": round(B.soft_ratio() * 100, 1),
    }
