def _s3(B):
    """3★：双门门墙 + 中央望楼 + 垛口端墩 + 金剑盾牌匾。

    语法是"要塞"：正面是一道**带垛口的门墙**，两个门洞并排，中央望楼穿墙而起。
    营房退到门后，蓝瓦顶只露出上半 —— 深度的层次就是这么来的。
    角塔在 1500 tri 的硬线里让位给垛口 + 端墩：剪影照样"咬住转角"，省 200 tri。
    """
    yard(B)
    sand(B, 0.104, (0.000, 0.330), n=8)
    curb(B, 0.840, 0.026, G, 0.016)

    # ---- 后部营房（退到门后，只露上半；不加隅石/台基，钱花在门墙上）
    W, D, YC = 0.620, 0.330, -0.275
    zt = stone_hall(B, W, D, G, 0.354, at=(0.0, YC), skirt=0.070, quoins=False,
                    plinth=False)
    for s in (-1, 1):
        B.box("营房扶壁%d" % s, 0.046, 0.060, 0.300, G, "石", 0.0,
              at=(s * (W / 2 - 0.020), YC + D / 2 - 0.020))
    roof(B, 0.660, 0.390, zt, zt + 0.276, 4, at=(0.0, YC), gold=True,
         gable_window=0.036)
    B.window("营房后窗", 0.048, 0.062, (0.0, YC - D / 2 - 0.006, G + 0.170),
             "洞", True, "石亮", "Y")

    # ---- 门墙（暗石：要塞的"下重上轻"）
    GW, GD, GY = 0.680, 0.140, -0.050
    B.box("门墙", GW, GD, 0.380, G, "石暗", 0.008, at=(0.0, GY))
    B.box("门墙裙", GW + 0.020, GD + 0.020, 0.054, G, "台基", 0.0, at=(0.0, GY))
    B.box("门墙檐", GW + 0.008, GD + 0.008, 0.010, G + 0.378, "石亮", 0.0, at=(0.0, GY))
    B.box("门墙木枋", GW + 0.008, GD + 0.008, 0.014, G + 0.352, "木暗", 0.0, at=(0.0, GY))
    for s in (-1, 1):
        door(B, s * 0.186, GY + GD / 2, G + 0.004, 0.118, 0.288, detail=1, studs=1)
    # 端塔：门墙两端加两座蓝顶小塔（素盒 + 檐 + 锥 = 30 tri/座）。
    # 这是 1500 硬线内最划算的一次剪影升级：门墙 0.47 → 端塔 0.65 → 望楼 1.42，三级台阶。
    for s in (-1, 1):
        # 端墩：比门墙高 9 cm，把"这一段是墙不是房"钉死；盾挂在墩上。
        # 试过升级成带蓝顶的角塔（+36 tri）：512 px 上读成两块贴上去的白盒子，
        # 反而把门墙的"一道墙"打断 —— 已回退。
        B.box("端墩%d" % s, 0.086, GD + 0.012, 0.090, G + 0.386, "石", 0.0,
              at=(s * 0.296, GY))
        shield(B, (s * 0.296, GY + GD / 2 + 0.010, G + 0.232), 0.032)
    crenel(B, -0.252, -0.118, GY + GD / 2 + 0.004, G + 0.386, 3, "石亮", 0.044, 0.034)
    crenel(B, 0.118, 0.252, GY + GD / 2 + 0.004, G + 0.386, 3, "石亮", 0.044, 0.034)

    # ---- 中央望楼（下段石身咬住门墙，上段提亮，顶上一圈木挑台 + 垛口 + 旗桅）
    BW = 0.250
    B.box("望楼下段", BW, 0.190, 0.510, G, "石暗", 0.008, at=(0.0, GY))
    B.box("望楼腰线", BW + 0.018, 0.208, 0.012, G + 0.510, "石亮", 0.0, at=(0.0, GY))
    z0u = G + 0.522
    B.box("望楼上段", BW - 0.012, 0.178, 0.382, z0u, "石", 0.007, at=(0.0, GY))
    B.box("望楼檐", BW + 0.026, 0.208, 0.014, z0u + 0.382, "石亮", 0.0, at=(0.0, GY))
    B.window("望楼窗", 0.022, 0.064, (0.0, GY + 0.094, z0u + 0.120), "洞",
             False, axis="Y")
    watch_top(B, BW - 0.012, 0.178, z0u + 0.396, "石", 3, 0.036, 0.046, at=(0.0, GY))
    mast(B, (0.0, GY), z0u + 0.472, z0u + 0.790, 0.112, 0.086)

    # ---- 金剑盾牌匾（望楼下段正面，抬到门楣之上）
    plaque(B, (0.0, GY + 0.096, G + 0.556), 0.162, 0.076)

    # ---- 前庭：中间留空，木人 / 枪架 / 桶 贴边
    dummy(B, (0.318, 0.398))
    rack(B, (-0.330, 0.238), G, 0.150, 0.176, 3, True)


# ================================================================ 入口

def build(star=3, name=None, pal=None):
    B = mkit.B(pal=pal, twoslot=True)
    B.base()
    B.groups = []
    fn = {1: _s1, 2: _s2, 3: _s3}[star]
    t0 = B.tris()
    fn(B)
    B.groups.append(("组件合计", B.tris() - t0))
    nm = name or ("兵营_%d星" % star)
    ob = B.join(nm)
    ob["star"] = star
    ob["palette"] = (pal if isinstance(pal, str) else mkit.DEFAULT_PALETTE)
    ob["slots"] = 2
    ob.data.calc_loop_triangles()
    return ob, B


def stats(ob, B):
    lo, hi = B.bbox()
    return {
        "name": ob.name,
        "tris": len(ob.data.loop_triangles),
        "verts": len(ob.data.vertices),
        "size": [round(hi[i] - lo[i], 4) for i in range(3)],
        "min": [round(lo[i], 5) for i in range(3)],
        "max": [round(hi[i], 5) for i in range(3)],
        "materials": [m.name for m in ob.data.materials],
        "team_area": round(B.team_area() * 100, 2),
        "soft": round(B.soft_ratio() * 100, 1),
    }
