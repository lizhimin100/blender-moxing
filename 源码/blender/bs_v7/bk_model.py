    x, y = at
    for s in (-1, 1):
        B.box("枪架柱%d" % s, 0.017, 0.017, h, z, role, 0.0,
              at=(x + s * (w / 2), y))
    B.box("枪架横", w + 0.024, 0.014, 0.015, z + h - 0.020, role, 0.0, at=(x, y))
    for i in range(spears):
        px = x + (i - (spears - 1) / 2) * (w / max(1, spears - 1) * 0.60)
        bar(B, "立矛%d" % i, (px, y + 0.004, z), (px, y + 0.012, z + h + 0.072),
            0.0065, "木", "铁", 0.011, 0.026)
    if crossed:
        for s in (-1, 1):
            bar(B, "交叉矛%d" % s, (x + s * 0.052, y - 0.018, z),
                (x - s * 0.030, y + 0.040, z + h + 0.096),
                0.0075, "木亮", "铁", 0.012, 0.030)


