def steps(B, w, n, z_bottom, z_top, y0, y1, role="石"):
    """台阶段：每级从门口往前长，绝不居中（居中会把最前一级顶出底座）。"""
    tread = (y1 - y0) / n
    hh = (z_top - z_bottom) / n
    for i in range(n):
        z = z_top - 0.004 - hh * (i + 1)
        B.box("台阶%d" % i, w, tread * (i + 1), hh, z, role, 0.0,
              at=(0.0, y0 + tread * (i + 1) / 2))


