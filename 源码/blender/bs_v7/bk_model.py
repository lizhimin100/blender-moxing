def tent(B, at, w=0.190, d=0.220, z=G, h=0.175, role="布", stripe=True):
    """蓝白帐篷：白帆布 + 队色纵条 + 深色门洞 + 脊杆。

    "蓝白"不能靠两种白 —— 必须有一条真的队色；不然 96 px 上就是一团米白。
    """
    x, y = at
    B.roof_gable_y("帐篷布", w, d, z, z + h, role, at=at)
    for s in (-1, 1):
        pts = [(-w / 2 + 0.008, 0.002), (w / 2 - 0.008, 0.002), (0.0, h - 0.010)]
        B.plate("帐篷端%d" % s, pts, 0.010, role, (x, y + s * d / 2, z), "Y")
    B.plate("帐篷门", [(-w * 0.24, 0.004), (w * 0.24, 0.004), (0.0, h * 0.62)],
            0.008, "洞", (x, y + d / 2 + 0.007, z), "Y")
    B.box("帐篷脊", 0.012, d + 0.020, 0.012, z + h - 0.004, "木暗", 0.0, at=(x, y))
    if stripe:
        L = math.hypot(w / 2, h)
        for s in (-1, 1):
            nx, nz = s * h / L, (w / 2) / L
            p0 = (x + s * w * 0.30, y - d * 0.34, z + h * 0.40)
            p1 = (x + s * w * 0.30, y + d * 0.34, z + h * 0.40)
            off = 0.0025
            quad = [(p0[0] + nx * off, p0[1], p0[2] + nz * off),
                    (p1[0] + nx * off, p1[1], p1[2] + nz * off),
                    (p1[0] + nx * off + s * 0.026, p1[1], p1[2] + nz * off - 0.030),
                    (p0[0] + nx * off + s * 0.026, p0[1], p0[2] + nz * off - 0.030)]
            B.slab4("帐篷条%d" % s, quad, 0.004, "旗")


