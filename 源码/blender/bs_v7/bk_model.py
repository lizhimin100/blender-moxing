def fence(B, x0, x1, y, z=G, h=0.150, n=3, rails=2, role="木", cap="木亮",
          cap_h=0.020, t=0.023):
    """木栅：柱 + 横杆。柱顶加小锥 —— 平头柱在 512 px 上读成"木条"。"""
    for i in range(n):
        x = x0 + (x1 - x0) * (i / max(1, n - 1))
        B.box("栅柱", t, t, h, z, role, 0.0, at=(x, y))
        B.pyramid("栅尖", t + 0.009, t + 0.009, cap_h, z + h - 0.002, cap, at=(x, y))
    for k in range(rails):
        zz = z + h * (0.28 + 0.36 * k)
        B.box("栅横", abs(x1 - x0) + t, 0.013, 0.015, zz, role, 0.0,
              at=((x0 + x1) / 2, y))


