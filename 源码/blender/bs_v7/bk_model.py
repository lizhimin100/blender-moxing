def _budget(B, store, name, fn, *a, **kw):
    """按组件记账：造型迭代时一眼看出钱花在哪。"""
    t0 = B.tris()
    fn(B, *a, **kw)
    store.append((name, B.tris() - t0))


def spike(B, name, p0, p1, r, role="铁", sides=4):
    """从 p0 指向 p1 的锥尖（枪头/箭镞）。4 边 = 6 tri，512 px 上够读。"""
    p0, p1 = Vector(p0), Vector(p1)
    d = p1 - p0
    L = d.length
    if L < 1e-6:
        return
    q = d.to_track_quat('Z', 'Y').to_matrix()
    v = []
    for i in range(sides):
        a = 2 * math.pi * i / sides
        v.append(tuple(p0 + q @ Vector((r * math.cos(a), r * math.sin(a), 0.0))))
    v.append(tuple(p1))
    f = [(i, (i + 1) % sides, sides) for i in range(sides)]
    f.append(tuple(range(sides - 1, -1, -1)))
    return B.part(name, v, f, role, 0.0, 1, "all")


def bar(B, name, p0, p1, r, role="木", tip=None, tip_r=None, tip_len=0.022):
    """杆件：方料 + 可选锥尖。长矛、旗杆都走它。"""
    B.beam(name, p0, p1, r * 2, r * 2, role, 0.0)
    if tip:
        a, b = Vector(p0), Vector(p1)
        d = (b - a).normalized()
        spike(B, name + "头", b - d * tip_len, b + d * 0.002, tip_r or r * 1.5, tip)


